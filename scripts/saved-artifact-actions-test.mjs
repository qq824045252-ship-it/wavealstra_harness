import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm, unlink, symlink, link } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { createHash } from 'node:crypto';
import { SavedArtifactActions } from '../src/main/artifact/SavedArtifactActions.ts';
const root = await mkdtemp(join(tmpdir(), 'saved-actions-test-'));
try {
  const storageRoot = join(root, 'host'), store = join(storageRoot, 'durable', 'a'.repeat(64), 'artifacts');
  await mkdir(store, { recursive: true });
  const bytes = Buffer.from('immutable saved version\n'), digest = createHash('sha256').update(bytes).digest('hex');
  const snapshotPath = join(store, digest + '.txt');
  await writeFile(snapshotPath, bytes);
  let destination, opened, calls = 0, dialog = async () => destination;
  const service = new SavedArtifactActions({ storageRoot, exportRoot: join(root, 'exports'), chooseDestination: () => dialog(), openPath: async path => { calls++; opened = path; return ''; } });
  const request = { snapshotPath, name: '../../report.exe' };
  await service.openSystem(request);
  assert.equal(calls, 1); assert(opened.endsWith('report.txt')); assert.notEqual(opened, snapshotPath);
  assert.deepEqual(await readFile(opened), bytes);
  await writeFile(opened, 'edited in default application');
  assert.deepEqual(await readFile(snapshotPath), bytes);
  assert.deepEqual(await service.saveAs(request), { canceled: true });
  destination = join(root, 'saved.txt');
  assert.equal((await service.saveAs(request)).canceled, false);
  assert.deepEqual(await readFile(destination), bytes);
  await writeFile(destination, 'replace me');
  await service.saveAs(request); assert.deepEqual(await readFile(destination), bytes);
  destination = snapshotPath;
  await assert.rejects(service.saveAs(request), /不能覆盖/);
  const source = join(root, 'original.txt'); await writeFile(source, 'new mutable content');
  await assert.rejects(service.openSystem({ snapshotPath: source, name: 'original.txt' }), /不是本应用/);
  const outside = join(root, 'artifacts', digest + '.txt'); await mkdir(join(root,'artifacts')); await writeFile(outside, bytes);
  await assert.rejects(service.openSystem({ snapshotPath: outside, name: 'x.txt' }), /不是本应用/);
  const hardlinked = join(root, 'hardlinked.txt'); await link(snapshotPath, hardlinked);
  destination = hardlinked; await assert.rejects(service.saveAs(request), /独立普通文件/);
  assert.deepEqual(await readFile(snapshotPath), bytes);
  const junction = join(root, 'redirect'); await symlink(storageRoot, junction, 'junction');
  destination = join(junction, 'overwrite.txt'); await assert.rejects(service.saveAs(request), /不能覆盖/);
  const badParent = join(root, 'missing-dir', 'result.txt'); destination = badParent;
  await assert.rejects(service.saveAs(request), /ENOENT/);
  const failing = new SavedArtifactActions({storageRoot, exportRoot: join(root,'exports'), chooseDestination: async()=>undefined, openPath: async()=> 'default app denied'});
  await assert.rejects(failing.openSystem(request), /default app denied/);
  await writeFile(snapshotPath, 'tampered'); await assert.rejects(service.openSystem(request), /完整性/);
  await writeFile(snapshotPath, bytes);
  destination = join(root, 'late.txt'); dialog = async () => { await unlink(snapshotPath); return destination; };
  await assert.rejects(service.saveAs(request), /ENOENT/);
  await assert.rejects(readFile(destination), /ENOENT/);
  console.log('saved artifact actions PASS: exact snapshot, separate editable system copy, name/extension safety, cancel, overwrite, protected storage, mutable/outside/tampered/missing rejection, dialog race, actual hardlink/junction, missing parent, external-app error');
} finally { await rm(root, { recursive: true, force: true }); }

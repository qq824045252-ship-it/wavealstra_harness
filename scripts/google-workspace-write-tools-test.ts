import assert from 'node:assert/strict';
import { BACKGROUND_CONTEXT } from '@earendil-works/chord/context';
import type { ToolExecutionApi } from '@earendil-works/pi-durable';
import { createGoogleWorkspaceWriteTools, workspaceWriteOperationId } from '../src/main/connectors/GoogleWorkspaceWriteTools';
import type { GoogleWorkspaceWriteService } from '../src/main/connectors/GoogleWorkspaceWriteService';
import { isSideEffectTool } from '../src/shared/pi-event-mapper';
import { isMyBuddyNativeExtensionToolName } from '../src/shared/native-tools';
const observed: Array<{ method: string; args: unknown; scope?: string }> = [];
const fake = Object.fromEntries(['sendMail','createEvent','updateEvent','getEvent'].map(method=>[method,async(args:unknown,_signal:unknown,scope?:string)=>{observed.push({method,args,scope});return {ok:true,data:{id:'result731'},checkedAt:1};}])) as unknown as GoogleWorkspaceWriteService;
let readOnly=false;
const tools=createGoogleWorkspaceWriteTools(fake,{resolveRequestScope:async()=> 'user-message731',readOnly:()=>readOnly});
assert.deepEqual(tools.map(t=>t.name),['calendar_get','gmail_send','calendar_create','calendar_update']);
assert.equal(observed.length,0);
const api={conversationId:'conv731',taskId:731,callId:'call731'} as unknown as ToolExecutionApi;
const mail={to:['alice@example.test'],subject:'Hello',body:'A body'};
const first=workspaceWriteOperationId('gmail_send','user-message731',mail);
assert.equal(first,workspaceWriteOperationId('gmail_send','user-message731',{body:mail.body,subject:mail.subject,to:mail.to}));
assert.notEqual(first,workspaceWriteOperationId('gmail_send','later-message',mail));
assert.notEqual(first,workspaceWriteOperationId('gmail_send','user-message731',{...mail,subject:'A different requested mail'}));
assert.notEqual(first,workspaceWriteOperationId('calendar_create','user-message731',mail));
assert.throws(()=>workspaceWriteOperationId('gmail_send','',mail));
for(const tool of tools){assert(isMyBuddyNativeExtensionToolName(tool.name));assert.equal(tool.replay,tool.name==='calendar_get'?'safe':'unsafe');assert.equal(isSideEffectTool(tool.name,{}),tool.name!=='calendar_get');}
const send=tools.find(t=>t.name==='gmail_send')!;
await send.execute(mail,api,BACKGROUND_CONTEXT);
const sent=observed[0].args as {operationId:string};assert.equal(sent.operationId,first);assert.equal(observed[0].scope,'user-message731');
await send.execute(mail,{...api,callId:'new-call',taskId:732} as ToolExecutionApi,BACKGROUND_CONTEXT);
assert.equal((observed[1].args as {operationId:string}).operationId,first,'new tool call must not bypass request idempotency');
await tools.find(t=>t.name==='calendar_create')!.execute({title:'Event',start:'2026-11-15',end:'2026-11-16',allDay:true},api,BACKGROUND_CONTEXT);
await tools.find(t=>t.name==='calendar_update')!.execute({id:'event731',etag:'v1',title:'New title'},api,BACKGROUND_CONTEXT);
assert.deepEqual(Object.keys(observed[3].args as object).sort(),['etag','id','operationId','title']);
assert.equal(observed[3].scope,'user-message731');
readOnly=true;
const before=observed.length;
for(const tool of tools.filter(t=>t.name!=='calendar_get')) await assert.rejects(tool.execute(mail,api,BACKGROUND_CONTEXT),/只读/);
assert.equal(observed.length,before,'readonly does not call writer');
await tools.find(t=>t.name==='calendar_get')!.execute({id:'event731'},api,BACKGROUND_CONTEXT);
assert.equal(observed.at(-1)?.method,'getEvent','readonly still permits fresh event reads');
await assert.rejects(createGoogleWorkspaceWriteTools(fake).find(t=>t.name==='gmail_send')!.execute(mail,api,BACKGROUND_CONTEXT),/原始用户请求/);
assert.equal(observed.length,before+1,'missing host identity fails closed');
console.log('PASS host request/payload identity across calls, readonly, missing identity, unsafe replay, metadata and exact changed fields');

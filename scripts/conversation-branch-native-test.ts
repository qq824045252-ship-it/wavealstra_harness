// Regression tests against the installed Pi SDK, real JSONL files and reloads.
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { mkdtempSync, readFileSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { SessionManager } from '@earendil-works/pi-coding-agent';
import { createConversationBranchSession, resolveConversationBranchLeaf } from '../src/main/agent/session-branch';
import { loadTaskHistoryFromSession } from '../src/main/agent/session-history';
import { getVisibleSessionUserMessages } from '../src/main/agent/session-user-messages';

const root = mkdtempSync(join(tmpdir(), 'mybuddy-branch-native-'));
let passed = 0, failed = 0;
function test(name: string, run: () => void): void {
  try { run(); passed++; console.log('PASS ' + name); }
  catch (error) { failed++; console.error('FAIL ' + name, error instanceof Error ? error.message : error); }
}
function make(name: string) { return SessionManager.create(join(root, name, 'work'), join(root, name, 'sessions')); }
function user(sm: SessionManager, text: string) { return sm.appendMessage({ role: 'user', content: text } as never); }
function answer(sm: SessionManager, text: string) { return sm.appendMessage({ role: 'assistant', content: [{ type: 'text', text }] } as never); }
function tool(sm: SessionManager, id: string) {
  sm.appendMessage({ role: 'assistant', content: [{ type: 'toolCall', id, name: 'write', arguments: { path: id + '.txt', content: id } }] } as never);
  sm.appendMessage({ role: 'toolResult', toolCallId: id, toolName: 'write', content: [{ type: 'text', text: 'ok' }], isError: false } as never);
}
try {
 test('native toolCall IDs are inherited without synthetic message fields', () => {
  const sm = make('provenance'); const u = user(sm, 'first'); tool(sm, 'before'); answer(sm, 'one');
  user(sm, 'second'); tool(sm, 'after'); answer(sm, 'two');
  const r = resolveConversationBranchLeaf(sm.getSessionFile()!, sm.getCwd(), { entryId: u, position: 'after_reply' });
  const ids = (r as unknown as { inheritedToolCallIds?: string[] }).inheritedToolCallIds;
  assert.deepEqual(ids, ['before']);
 });
 test('user-only fork keeps labels regenerated by Pi', () => {
  const sm = make('labels'); const u = user(sm, 'first'); answer(sm, 'parent reply'); sm.appendLabelChange(u, 'KEEP');
  const before = createHash('sha256').update(readFileSync(sm.getSessionFile()!)).digest('hex');
  const child = createConversationBranchSession(sm.getSessionFile()!, join(root, 'labels-child'), u);
  const reloaded = SessionManager.open(child.sessionFile);
  assert.equal(reloaded.getLabel(u), 'KEEP');
  assert.equal(reloaded.getHeader()?.parentSession, sm.getSessionFile());
  assert.notEqual(reloaded.getSessionId(), sm.getSessionId());
  assert.deepEqual(reloaded.buildSessionContext().messages.map(m => m.role), ['user']);
  answer(reloaded, 'child reply');
  assert.equal(SessionManager.open(child.sessionFile).getLabel(u), 'KEEP');
  assert.equal(createHash('sha256').update(readFileSync(sm.getSessionFile()!)).digest('hex'), before);
 });
 test('fallback UI index ignores user messages filtered from history', () => {
  const sm = make('filtered'); user(sm, ''); answer(sm, 'invisible turn'); const visible = user(sm, 'visible'); answer(sm, 'reply');
  assert.equal(loadTaskHistoryFromSession(sm.getSessionFile()!).messages.filter(m => m.role === 'user').length, 1);
  const r = resolveConversationBranchLeaf(sm.getSessionFile()!, sm.getCwd(), { userMessageIndex: 0, position: 'after_user' });
  assert.equal(r.userEntryId, visible);
 });
 test('fallback UI index follows full displayed branch after compaction', () => {
  const sm = make('compaction'); const old = user(sm, 'old'); answer(sm, 'old reply'); const kept = user(sm, 'kept'); answer(sm, 'kept reply');
  sm.appendCompaction('earlier summary', kept, 500);
  assert.deepEqual(loadTaskHistoryFromSession(sm.getSessionFile()!).messages.filter(m => m.role === 'user').map(m => m.entryId), [old, kept]);
  assert.equal(sm.buildContextEntries().filter(e => e.type === 'message' && e.message.role === 'user').length, 1);
  for (const [index, expected] of [old, kept].entries()) {
    const r = resolveConversationBranchLeaf(sm.getSessionFile()!, sm.getCwd(), { userMessageIndex: index, position: 'after_reply' });
    assert.equal(r.userEntryId, expected);
  }
 });
 test('fork excludes abandoned branch and future messages', () => {
  const sm = make('tree'); const u = user(sm, 'root'); const a = answer(sm, 'shared');
  user(sm, 'abandoned'); answer(sm, 'abandoned answer'); sm.branch(a);
  const active = user(sm, 'active'); answer(sm, 'active answer'); user(sm, 'future'); answer(sm, 'future answer');
  const r = resolveConversationBranchLeaf(sm.getSessionFile()!, sm.getCwd(), { entryId: active, position: 'after_user' });
  const child = createConversationBranchSession(sm.getSessionFile()!, sm.getCwd(), r.leafEntryId);
  const cm = SessionManager.open(child.sessionFile);
  assert.deepEqual(cm.getBranch().filter(e => e.type === 'message' && e.message.role === 'user').map(e => e.id), [u, active]);
  assert(!JSON.stringify(cm.getEntries()).includes('abandoned'));
  assert(!JSON.stringify(cm.getEntries()).includes('future'));
 });
 test('current visible user selector excludes every abandoned branch', () => {
  const sm = make('user-selector'); user(sm, 'shared'); const a = answer(sm, 'shared reply');
  user(sm, 'abandoned'); answer(sm, 'old reply'); sm.branch(a);
  const selected = user(sm, 'current'); answer(sm, 'current reply');
  assert.deepEqual(getVisibleSessionUserMessages(sm).map(m => m.text), ['shared', 'current']);
  assert.equal(getVisibleSessionUserMessages(sm)[1].entryId, selected);
  assert.equal(sm.getEntries().filter(e => e.type === 'message' && e.message.role === 'user').length, 3);
 });
 test('user-only child can be immediately forked again and reloaded', () => {
  const sm = make('nested'); const u = user(sm, 'start'); answer(sm, 'source reply');
  const c = createConversationBranchSession(sm.getSessionFile()!, sm.getCwd(), u);
  const g = createConversationBranchSession(c.sessionFile, sm.getCwd(), u);
  const gm = SessionManager.open(g.sessionFile);
  assert.equal(gm.getHeader()?.parentSession, c.sessionFile);
  answer(gm, 'grandchild');
  assert.equal(SessionManager.open(g.sessionFile).buildSessionContext().messages.length, 2);
  assert.equal(SessionManager.open(c.sessionFile).buildSessionContext().messages.length, 1);
 });
} finally { rmSync(root, { recursive: true, force: true, maxRetries: 5, retryDelay: 100 }); }
console.log(`conversation-branch-native: passed=${passed} failed=${failed}`);
if (failed) process.exitCode = 1;

import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync, readFileSync, unlinkSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { AppDatabase } from "../src/main/db/AppDatabase";
import { BotRegistry } from "../src/main/agent/work/BotRegistry";
import { BotConversationRepository } from "../src/main/agent/work/BotConversationRepository";
import { snapshotBotAttachments } from "../src/main/agent/work/BotAttachmentStorage";
import { prepareBotAttachmentInput, BotAttachmentInputError } from "../src/main/agent/work/BotAttachmentInput";
import { botSendSchema } from "../src/shared/bot-conversation";
import { DEFAULT_BOT_ID, LOCAL_USER_ID } from "../src/shared/bot-work";
import { WorkService, DESKTOP_USER_GRANTS } from "../src/main/agent/work/WorkService";

const root = mkdtempSync(join(tmpdir(), "bot-attachments-"));
let db = new AppDatabase(join(root, "app.db"));
try {
  new BotRegistry(db.connection).registerBot({ userId: LOCAL_USER_ID, botId: DEFAULT_BOT_ID, displayName: "attachment fixture", authorization: DESKTOP_USER_GRANTS });
  const source = join(root, "report.txt"); writeFileSync(source, "attachment evidence: violet-731");
  const request = botSendSchema.parse({ botId: DEFAULT_BOT_ID, requestId: "attachment-request", text: "", attachments: [{ name: "report.txt", path: source }] });
  assert(!botSendSchema.safeParse({ ...request, attachments: [] }).success);
  assert(!botSendSchema.safeParse({ ...request, attachments: Array(11).fill(request.attachments![0]) }).success);
  const stored = snapshotBotAttachments(root, `${LOCAL_USER_ID}:${DEFAULT_BOT_ID}:${request.requestId}`, request.attachments!);
  assert.notEqual(stored[0].path, source); assert.equal(readFileSync(stored[0].path, "utf8"), "attachment evidence: violet-731");
  let repo = new BotConversationRepository(db.connection);
  const receipt = db.connection.transaction(() => repo.accept(LOCAL_USER_ID, request, stored))();
  assert.deepEqual(repo.message(receipt.userMessageId)?.attachments, stored);
  const works = new WorkService(db.connection, { bots: new BotRegistry(db.connection) });
  const actor = { kind: "user" as const, userId: LOCAL_USER_ID, grants: DESKTOP_USER_GRANTS };
  const created = works.createWork(actor, { operationId: "attachment-work", title: "long goal attachment", goalDescription: "g".repeat(4000), inputSnapshotId: "snapshot-files", authorization: DESKTOP_USER_GRANTS });
  assert(created.ok); if (!created.ok) throw new Error("fixture create failed");
  const multiple = Array.from({ length: 10 }, (_, index) => {
    const path = join(root, `material-${index}.txt`); writeFileSync(path, `material ${index}`);
    return { name: `material-${index}.txt`, path };
  });
  const multiRequest = botSendSchema.parse({ ...request, requestId: "multiple-files", attachments: multiple });
  const multiStored = snapshotBotAttachments(root, "multiple-files", multiple);
  repo.accept(LOCAL_USER_ID, multiRequest, multiStored);
  const sourceReceipt = repo.receipt(LOCAL_USER_ID, DEFAULT_BOT_ID, multiRequest.requestId)!;
  repo.linkWorkAttachments(sourceReceipt, created.work.workId, created.work.inputSnapshotId);
  const bound = works.dispatchExecution(actor, { workId: created.work.workId, operationId: "attachment-execution", botId: DEFAULT_BOT_ID, taskId: "attachment-task", durableStoreKey: "attachment-store", conversationId: "attachment-conversation", workspaceBinding: root });
  assert(bound.ok); if (!bound.ok) throw new Error("fixture dispatch failed");
  const binding = works.repo.listBindings(created.work.workId)[0]!;
  assert.equal(created.work.goalDescription?.length, 2000);
  assert(multiStored.every(item => works.repo.attachmentInput(binding).includes(item.path)), "long human goal cannot truncate structured attachment input");
  repo.linkWorkAttachments(sourceReceipt, created.work.workId, "amended-snapshot", created.work.inputSnapshotId);
  assert(multiStored.every(item => works.repo.attachmentInput({ ...binding, inputSnapshotId: "amended-snapshot" }).includes(item.path)));
  assert.equal(works.repo.attachmentInput({ ...binding, inputSnapshotId: "unrelated-snapshot" }), "", "other execution input cannot inherit unrelated attachments");
  unlinkSync(source);
  assert(repo.accept(LOCAL_USER_ID, request).replayed, "replay validates identity without reading removed source");
  assert.throws(() => repo.accept(LOCAL_USER_ID, { ...request, attachments: [{ name: "other.txt", path: source }] }), /不同正文、附件/);
  db.close(); db = new AppDatabase(join(root, "app.db")); repo = new BotConversationRepository(db.connection);
  assert.deepEqual(repo.history(LOCAL_USER_ID, { botId: DEFAULT_BOT_ID }).messages[0].attachments, stored);
  assert.equal(readFileSync(stored[0].path, "utf8"), "attachment evidence: violet-731", "restart keeps immutable bytes after original removal");
  assert.throws(() => snapshotBotAttachments(root, "missing", request.attachments!), /不可用/);
  assert.throws(() => snapshotBotAttachments(root, "directory", [{ name: "folder", path: root }]), /不是普通文件/);
  const oversized = join(root, "huge.png"); writeFileSync(oversized, Buffer.alloc(12 * 1024 * 1024 + 1));
  assert.throws(() => snapshotBotAttachments(root, "large", [{ name: "huge.png", path: oversized }]), /12 MB/);
  const input = await prepareBotAttachmentInput({ text: "", attachments: stored, model: { input: ["text"] }, directory: root, requestId: "text" });
  assert(JSON.stringify(input).includes("violet-731"));
  const image = join(root, "sample.png"); const png = Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+aFOsAAAAASUVORK5CYII=", "base64"); writeFileSync(image, png);
  const imageOptions = { text: "image", attachments: [{ name: "sample.png", path: image }], model: { input: ["text", "image"] }, directory: root, requestId: "image" };
  const imageInput = await prepareBotAttachmentInput(imageOptions);
  assert(Array.isArray(imageInput) && imageInput.some(block => block.type === "image" && block.data === png.toString("base64")));
  await assert.rejects(() => prepareBotAttachmentInput({ ...imageOptions, model: { input: ["text"] } }), BotAttachmentInputError);
  const fallback = await prepareBotAttachmentInput({ ...imageOptions, model: { input: ["text"] }, visionFallback: async paths => { assert.deepEqual(paths, [image]); return "real fallback fixture"; } });
  assert(JSON.stringify(fallback).includes("real fallback fixture"));
  const pdf = join(root, "document.pdf"); writeFileSync(pdf, "%PDF fixture");
  const pdfInput = await prepareBotAttachmentInput({ ...imageOptions, attachments: [{ name: "document.pdf", path: pdf }] });
  assert(JSON.stringify(pdfInput).includes("尚未解析内容"));
  await assert.rejects(() => prepareBotAttachmentInput({ ...imageOptions, attachments: request.attachments! }), /无法读取/);
  console.log("PASS Bot attachment-only contract, stable copies, payload identity, restart, missing/oversize files, inline text, vision capability and honest document fallback");
} finally { db.close(); rmSync(root, { recursive: true, force: true }); }

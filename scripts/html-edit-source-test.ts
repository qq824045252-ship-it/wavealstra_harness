import { strict as assert } from "node:assert";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { HtmlSource, htmlHash, saveHtmlFile } from "../src/main/html-edit/HtmlSource";

const html = '\uFEFF<!doctype html>\r\n<html><head><meta charset="UTF-8"><style>p {color:red}</style></head><body>\r\n<p id="title" style="color: red">标题 <b>原文</b></p>\r\n<p>可删除</p><table><tr><td>单元格</td></tr></table><div><input value="42"></div><script>const x = "<p>JS</p>";document.querySelector("input").value=99;</script>\r\n</body></html>';
const source = new HtmlSource(html);
const title = source.nodes.find(n => n.html.includes("标题"))!;
assert.ok(title); assert.equal(title.deletable, false);
assert.equal(source.nodes.length, 3, "scripts, controls and nested containers excluded");
assert.equal(source.apply([]), html, "no-op is byte-identical including BOM and CRLF");
assert.equal(source.apply([{ key: title.key, html: '新标题 <b>文字</b>' }]), html.replace('标题 <b>原文</b>', '新标题 <b>文字</b>'), "only selected source range changes");
assert.ok(source.apply([{ key: title.key, html: title.html, align: "center" }]).includes('style="color: red;text-align:center"'));
assert.throws(() => source.apply([{ key: title.key, html: "", deleted: true }]), /不能直接删除/);
const removable = source.nodes.find(n => n.html === "可删除")!;
assert.equal(source.apply([{ key: removable.key, html: "", deleted: true }]), html.replace('<p>可删除</p>', ''));
for (const bad of ['<script>alert(1)</script>', '<img src=x onerror=alert(1)>', '<a href="java&#x73;cript:alert(1)">x</a>', '<span style="background-image:url(https://x)">x</span>', '<b onclick="alert(1)">x</b>', '<svg><text>x</text></svg>']) assert.throws(() => source.apply([{ key: title.key, html: bad }]));
assert.throws(() => source.apply([{ key: "unknown", html: "x" }]), /失效/);
assert.throws(() => source.apply([{ key: title.key, html: "x" }, { key: title.key, html: "y" }]), /失效/);
const ids = new HtmlSource('<p>Text <span id="keep">here</span></p>');
assert.throws(() => ids.apply([{ key: ids.nodes[0].key, html: "removed ID" }]), /ID/);
assert.throws(() => new HtmlSource('<meta charset="gbk"><p>hello</p>'), /UTF-8/);
const root = mkdtempSync(join(tmpdir(), "mybuddy-html-source-")), file = join(root, "source.html");
writeFileSync(file, html, "utf8");
const next = source.apply([{ key: title.key, html: "已保存" }]);
const backup = saveHtmlFile(file, htmlHash(html), next);
assert.equal(readFileSync(backup, "utf8"), html); assert.equal(readFileSync(file, "utf8"), next);
assert.throws(() => saveHtmlFile(file, htmlHash(html), "overwrite"), /已被修改/);
assert.equal(readFileSync(file, "utf8"), next, "concurrent stale writer never overwrites");
console.log("HTML edit source checks passed: offsets, inline validation, IDs, encoding, backup, stale-file conflict");

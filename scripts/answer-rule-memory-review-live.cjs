const assert = require("node:assert/strict");
const fs = require("node:fs/promises");
const path = require("node:path");
const { run } = require("./desktop-dev-harness.cjs");
const { routingControls } = require("./answer-routing-desktop-controls.cjs");

run(async env => {
  const { evaluate, until, requests, home, report } = env;
  const { click, fill, expand, openSettings, screenshot, askInChat } = routingControls(env);
  const api = (name, ...args) => evaluate("window.api." + name + "(" + args.map(arg => JSON.stringify(arg)).join(",") + ")");
  const original = "写项目周报时，只有提测记录的功能不可写成已上线。";
  const source = await api("memory.create", { title: "发布状态口径", content: original, kind: "constraint", scopeType: "global", sourceType: "manual", explicit: true });
  const extra = await api("memory.create", { title: "缺少发布记录", content: "写项目周报时逐项列出发布记录编号。查不到编号时写「待核实」。",
    kind: "procedure", scopeType: "global", sourceType: "manual", explicit: true });
  const conflict = await api("memory.create", { title: "相反口径", content: "写项目周报时，一律将已提测的功能算作已上线。",
    kind: "constraint", scopeType: "global", sourceType: "manual", explicit: true });
  const workspace = path.join(home, "周报目录");
  await fs.mkdir(workspace);
  await fs.writeFile(path.join(workspace, "release.md"), "交付记录 RG-174，蓝桥只完成提测，尚未上线。");
  await api("db.upsertSpace", { id: "review-space", name: "周报", path: workspace });
  await openSettings();
  await click("新增规则");
  await fill('[aria-label="遇到什么问题"]', "项目周报");
  await expand("匹配问法与例外");
  await fill('.answer-rule-form input[maxlength="90"]', "交付周报");
  await fill("#answer-rule-include", "项目周报");
  await fill("#answer-rule-instruction", "编写项目周报时，不能把只完成提测的功能列为上线。另外，列出每一项的记录编号。");
  await evaluate(`(() => {const s=[...document.querySelectorAll('.answer-rule-form select')].find(s=>[...s.options].some(o=>o.value==='task-file'));
    s.value='task-file';s.dispatchEvent(new Event('change',{bubbles:true}));})()`);
  await fill("#answer-rule-file", "release.md");
  const before = requests.length;
  await click("AI 去重并提炼");
  await until(() => evaluate("!!document.querySelector('.answer-rule-distillation') || !!document.querySelector('.answer-rule-memory-check [role=alert]')"), "AI distillation");
  const proposal = await evaluate("document.querySelector('.answer-rule-distillation textarea')?.value");
  assert.ok(proposal, await evaluate("document.querySelector('.answer-rule-memory-check').innerText"));
  assert.match(proposal, /待核实/);
  assert.match(proposal, /编号/);
  assert.match(proposal, /提测/);
  await screenshot("ai-memory-review");
  await expand("查看比对依据");
  assert.equal(requests.length - before, 1, "one authoring request compares all candidates");
  const findings = await evaluate("[...document.querySelectorAll('.answer-rule-memory-match')].map(n=>n.innerText)");
  assert.ok(findings.some(text => text.includes("可能冲突") && text.includes(conflict.title)), JSON.stringify(findings));
  assert.ok(findings.some(text => text.includes(source.title)), JSON.stringify(findings));
  assert.ok((await evaluate("document.querySelector('.answer-rule-distillation').innerText")).includes(extra.title));
  await fill(".answer-rule-distillation textarea", proposal + " 最后一行写交付状态。");
  await click("采用为独立草稿");
  assert.deepEqual(await api("answerRouting.list"), []);
  await click("保存规则");
  await until(() => api("answerRouting.list").then(rules => rules.length === 1), "reviewed rule stored");
  const [rule] = await api("answerRouting.list");
  assert.equal(rule.sourceMemoryId, null);
  assert.equal(rule.evidenceFile, "release.md");
  assert.equal(rule.instruction, proposal + " 最后一行写交付状态。");
  assert.equal((await api("memory.get", source.id)).content, original);
  await api("memory.forget", conflict.id);
  const taskId = "review-turn", question = "请按发布状态口径写项目周报，列出蓝桥的状态与编号。";
  await api("db.upsertTask", { id: taskId, title: taskId, spaceId: "review-space", welcomeMode: "general", updatedAt: Date.now() });
  const edit = "把全局的「交付周报」回答规则去重并提炼，保留缺编号时待核实和其余原有要求，增加一项：在回答末尾写「蓝桥回执」。直接保存，并测试「写项目周报」能否命中。";
  await env.restart();
  await env.rpc("Emulation.setFocusEmulationEnabled", {enabled:true});
  await evaluate(`import('/src/store/appStore.ts').then(({useAppStore}) => {
    const store=useAppStore.getState(); store.setSettingsOpen(false); store.setActiveTask('review-turn');
  })`);
  const managed = await askInChat(taskId, edit);
  const [revised] = await api("answerRouting.list");
  assert.equal(revised.id, rule.id);
  assert.ok(revised.revision > rule.revision, "chat must persist its edit");
  assert.match(revised.instruction, /蓝桥回执/);
  assert.equal(revised.evidenceFile, "release.md");
  assert.match(revised.instruction, /待核实/);
  assert.deepEqual(managed.uses, []);
  const turnStart = requests.length;
  const { answer, uses: [use] } = await askInChat(taskId, question);
  const first = requests.slice(turnStart).find(req => req.messages.some(m => m.role === "user" && JSON.stringify(m.content).includes(question)));
  const payload = JSON.stringify(first?.messages);
  assert.ok(payload.includes("蓝桥回执"));
  assert.match(payload, /交付记录 RG-174/);
  assert.equal(use.revision, revised.revision);
  assert.equal(use.evidence.status, "read");
  assert.match(answer, /RG-174/);
  assert.match(answer, /提测/);
  assert.match(answer, /蓝桥回执/);
  report.review = { findings, proposal, rule, revised, use, answer };
  const weatherMemory = (title, content) => api("memory.create", {title, content, kind:"procedure", scopeType:"global", sourceType:"manual", explicit:true});
  const lookup = await weatherMemory("天气单源查询", "查天气只查一轮，以中国气象局为首选。2026-11-16 查询杭州用站号58457，其他城市换站。");
  const validate = await weatherMemory("天气来源校验", "气象接口返回 code=0 才采用，缺少逐小时数据就说明只能提供全天预报。");
  await weatherMemory("天气规则启用记录", "天气查询规则已经全局启用，旧规则编号 R-META-937，版本 7。");
  const weather = await api("answerRouting.reviewMemory", { title:"出行天气", include:["天气"], exclude:["翻译"],
    instruction:"查询出行天气时按用户指定的城市给出预报和来源。" });
  assert.ok(weather.distillation);
  const method = weather.distillation.instruction;
  assert.match(method, /气象局/);
  assert.match(method, /(?:一|1|单)\s*(?:轮|次)/);
  assert.match(method, /code.{0,10}0/i);
  assert.match(method, /逐小时|小时级/);
  assert.doesNotMatch(method, /R-META-937|2026-11-16/);
  if (method.includes("58457")) assert.match(method, /杭州.{0,25}58457|58457.{0,25}杭州/);
  assert.ok(weather.distillation.exclude.includes("翻译"));
  assert.ok([lookup.id, validate.id].every(id => weather.distillation.sources.some(source => source.memoryId === id)));
  report.weatherDistillation = weather.distillation;

}, { name: "answer-rule-memory-review", liveModel: true, watchRenderer: false, settings: { memoryEnabled: true }, rpcTimeoutMs: 150000 });

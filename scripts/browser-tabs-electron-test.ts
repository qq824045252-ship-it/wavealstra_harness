import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { createServer } from "node:http";
import { app, BrowserWindow, shell, webContents } from "electron";
import { BrowserHost } from "../src/main/browser/BrowserHost";

const profiles = join(process.cwd(), "out/tests/browser-tabs-profiles");
mkdirSync(profiles, { recursive: true });
const root = mkdtempSync(join(profiles, "isolated-"));
app.setPath("userData", join(root, "profile"));
app.on("window-all-closed", () => {});
const checks: string[] = [];
const external: string[] = [];
const originalExternal = shell.openExternal;
shell.openExternal = async (url: string) => { external.push(url); };
let sourceVersion = 1;
const server = createServer((req, res) => {
  const title = req.url?.split("?")[0] ?? "/";
  res.setHeader("content-type", "text/html; charset=utf-8");
  res.end(`<title>${title}</title><h1>${title}</h1><input id="draft"><p id="source">${sourceVersion}</p><a id="popup" href="/popup" target="_blank">Popup</a><button id="blank" onclick="window.open('about:blank')">Blank</button><script>window.created = Math.random(); document.cookie='fixture=shared;path=/';</script>`);
});
const delay = (ms: number) => new Promise(resolve => setTimeout(resolve, ms));
async function until(predicate: () => boolean, label: string) {
  for (let i = 0; i < 200; i++) { if (predicate()) return; await delay(20); }
  throw new Error(`Timed out: ${label}`);
}
let host: BrowserHost | undefined;
let win: BrowserWindow | undefined;
let fail: unknown;
const timeout = setTimeout(() => { console.error("browser tabs test timed out"); app.exit(1); }, 45_000);
void (async () => {
  await app.whenReady();
  await new Promise<void>(resolve => server.listen(0, "127.0.0.1", resolve));
  const base = `http://127.0.0.1:${(server.address() as { port: number }).port}`;
  win = new BrowserWindow({ show: false, width: 1000, height: 800 });
  await win.loadURL("data:text/html,Isolated managed tab regression");
  let allowUnload = false;
  let unloadPrompts = 0;
  host = new BrowserHost(() => { unloadPrompts++; return allowUnload; });
  host.attach(win);
  const legacy = host.inspectionWebContents!;
  await host.navigateForAutomation(`${base}/legacy`);
  host.close();
  assert.equal(legacy.isDestroyed(), false);
  assert.equal(host.inspectionWebContents, legacy);
  console.log("PASS group", checks.length + 1); checks.push("legacy open/close retains document and exact WebContents");

  host.open(`${base}/a`, { key: "gadget:a", taskId: "task-one", gadgetId: "a" });
  const aId = host.activeTabId!;
  const a = host.getTabHost(aId)!;
  const aWc = a.inspectionWebContents!;
  await until(() => aWc.getURL() === `${base}/a` && !aWc.isLoading(), "load A");
  await aWc.executeJavaScript("document.querySelector('#draft').value='unsaved A'; window.counter=42");
  const aCreated = await aWc.executeJavaScript("window.created");
  host.setBounds({ x: 10, y: 80, width: 800, height: 600 });
  host.open(`${base}/b`, { key: `url:${base}/b`, taskId: "task-one" });
  const bId = host.activeTabId!;
  const b = host.getTabHost(bId)!;
  const bWc = b.inspectionWebContents!;
  await until(() => bWc.getURL() === `${base}/b` && !bWc.isLoading(), "load B");
  assert.notEqual(aWc.id, bWc.id);
  assert.equal(aWc.isDestroyed(), false);
  host.open(`${base}/a`, { key: "gadget:a", taskId: "task-one", gadgetId: "a" });
  assert.equal(host.activeTabId, aId);
  assert.equal(await aWc.executeJavaScript("document.querySelector('#draft').value"), "unsaved A");
  assert.equal(await aWc.executeJavaScript("window.created"), aCreated);
  assert.equal(await aWc.executeJavaScript("window.counter"), 42);
  await a.navigateForAutomation(`${base}/a`);
  assert.equal(await aWc.executeJavaScript("window.created"), aCreated);
  console.log("PASS group", checks.length + 1); checks.push("A → B → A preserves unsaved input, JS state and WebContents identity");

  const taskTwo = host.ensureTab({ key: "gadget:a", taskId: "task-two", gadgetId: "a", activate: false });
  const other = host.getTabHost(taskTwo.id)!;
  assert.notEqual(other.inspectionWebContents?.id, aWc.id);
  await other.navigateForAutomation(`${base}/task-two`);
  assert.equal(host.activeTabId, aId);
  assert.equal(await aWc.executeJavaScript("document.querySelector('#draft').value"), "unsaved A");
  host.selectTab(bId);
  const background = aWc.executeJavaScript("new Promise(resolve=>setTimeout(()=>resolve(document.querySelector('#draft').value),100))");
  host.selectTab(taskTwo.id);
  assert.equal(await background, "unsaved A");
  await a.navigateForAutomation(`${base}/a`);
  assert.equal(host.activeTabId, taskTwo.id);
  console.log("PASS group", checks.length + 1); checks.push("task ownership and in-flight fixed page handles survive UI tab changes");

  host.selectTab(aId);
  const beforePopup = host.listTabs().length;
  await aWc.executeJavaScript("document.querySelector('#popup').click()", true);
  await until(() => host!.listTabs().length === beforePopup + 1, "popup tab");
  const popup = host.listTabs().find(tab => tab.openerTabId === aId)!;
  const popupWc = host.getTabHost(popup.id)!.inspectionWebContents!;
  await until(() => popupWc.getURL() === `${base}/popup` && !popupWc.isLoading(), "popup loaded");
  assert.equal(popup.taskId, "task-one");
  assert.equal(popup.gadgetId, "a");
  assert.equal(aWc.getURL(), `${base}/a`);
  assert.equal(await aWc.executeJavaScript("document.querySelector('#draft').value"), "unsaved A");
  assert.equal(popupWc.session, aWc.session);
  assert.match(await popupWc.executeJavaScript("document.cookie"), /fixture=shared/);
  assert.equal(external.length, 0);
  assert.equal(BrowserWindow.getAllWindows().length, 1);
  console.log("PASS group", checks.length + 1); checks.push("target=_blank creates an owned in-app tab with the same session, never replaces source");

  host.selectTab(aId);
  await aWc.executeJavaScript("window.child=window.open('about:blank'); window.child.document.write('<title>Script popup</title><input id=child value=opener-preserved>')", true);
  await until(() => host!.listTabs().length === beforePopup + 2, "about blank popup");
  const scriptPopup = host.listTabs().find(tab => tab.openerTabId === aId && tab.id !== popup.id)!;
  const scriptWc = host.getTabHost(scriptPopup.id)!.inspectionWebContents!;
  assert.equal(await scriptWc.executeJavaScript("document.querySelector('#child').value"), "opener-preserved");
  assert.equal(await scriptWc.executeJavaScript("window.opener !== null"), true);
  console.log("PASS group", checks.length + 1); checks.push("window.open about:blank preserves opener scripting instead of losing the popup");

  host.selectTab(bId);
  const beforeUpdate = await aWc.executeJavaScript("window.created");
  sourceVersion = 2;
  host.markGadgetUpdated("a");
  assert.equal(host.activeTabId, bId, "source update does not activate background Gadget");
  assert.equal(await aWc.executeJavaScript("window.created"), beforeUpdate, "marking dirty does not reload a background page");
  host.selectTab(aId);
  await until(() => !aWc.isLoading(), "dirty Gadget refresh");
  assert.equal(await aWc.executeJavaScript("document.querySelector('#source').textContent"), "2");
  const afterUpdate = await aWc.executeJavaScript("window.created");
  host.selectTab(bId); host.selectTab(aId);
  assert.equal(await aWc.executeJavaScript("window.created"), afterUpdate, "dirty refresh consumed once");
  console.log("PASS group", checks.length + 1); checks.push("background Gadget source update refreshes once on selection without stealing focus");

  host.selectTab(aId);
  await aWc.executeJavaScript("window.onbeforeunload=e=>{e.preventDefault();e.returnValue='unsaved'}; navigator.userActivation.hasBeenActive", true);
  sourceVersion = 3;
  const beforeCancelledRefresh = await aWc.executeJavaScript("window.created");
  host.markGadgetUpdated("a"); host.selectTab(aId);
  await until(() => unloadPrompts === 1 && !aWc.isLoading(), "cancel dirty refresh");
  assert.equal(await aWc.executeJavaScript("window.created"), beforeCancelledRefresh);
  allowUnload = true;
  const refreshed = new Promise<void>(resolve => aWc.once("did-finish-load", () => resolve()));
  host.hardReload(); await refreshed;
  assert.equal(await aWc.executeJavaScript("document.querySelector('#source').textContent"), "3");
  assert.equal(unloadPrompts, 2);
  allowUnload = false;
  await aWc.executeJavaScript("window.onbeforeunload=e=>{e.preventDefault();e.returnValue='unsaved'}; navigator.userActivation.hasBeenActive", true);
  console.log("PASS group", checks.length + 1); checks.push("cancelled dirty refresh keeps the document and permits a later explicit refresh");
  host.closeTab(aId);
  await until(() => unloadPrompts === 3, "close confirmation");
  assert.equal(aWc.isDestroyed(), false);
  assert(host.getTabHost(aId));
  allowUnload = true;
  host.closeTab(aId);
  await until(() => aWc.isDestroyed(), "confirmed close");
  assert.equal(host.getTabHost(aId), null);
  assert.equal(unloadPrompts, 4);
  assert.equal(popupWc.isDestroyed(), false, "popup tab outlives its closed opener");
  assert.equal(scriptWc.isDestroyed(), false, "script popup tab outlives its closed opener");
  console.log("PASS group", checks.length + 1); checks.push("explicit close honors cancelled beforeunload then destroys confirmed WebContents");

  host.selectTab(bId);
  host.hide();
  host.addBlocker("test-dialog");
  host.selectTab(taskTwo.id);
  host.setBounds({ x: 10, y: 80, width: 800, height: 600 });
  assert.equal(host.visible, false);
  host.removeBlocker("test-dialog");
  assert.equal(host.visible, true);
  sourceVersion = 2;
  await b.navigateForAutomation(`${base}/b`, undefined, { reload: true });
  assert.equal(await bWc.executeJavaScript("document.querySelector('#source').textContent"), "2");
  console.log("PASS group", checks.length + 1); checks.push("global blockers survive tab changes; explicit source reload updates the fixed page");

  const ownedIds = host.listTabs().map(tab => host!.getTabHost(tab.id)!.inspectionWebContents!.id);
  host.dispose();
  assert.equal(host.attached, false);
  assert.equal(host.listTabs().length, 0);
  await until(() => ownedIds.every(id => !webContents.fromId(id)), "all contents destroyed after dispose");
  for (const id of ownedIds) assert.equal(webContents.fromId(id), undefined);
  assert.equal(win.contentView.children.length, 0);
  console.log("PASS group", checks.length + 1); checks.push("dispose destroys all tab contents and detaches every native child view");
  console.log(`browser managed tabs Electron: PASS (${checks.length} behaviour groups)`);
})().catch(error => { fail = error; console.error(error); }).finally(() => {
  const output = join(process.cwd(), "out/diagnostics/browser-tabs");
  mkdirSync(output, { recursive: true });
  writeFileSync(join(output, "electron-results.json"), JSON.stringify({ electron: process.versions.electron, checks, error: fail ? String(fail) : undefined }, null, 2));
  shell.openExternal = originalExternal;
  host?.dispose();
  if (win && !win.isDestroyed()) win.destroy();
  server.close(); clearTimeout(timeout); app.exit(fail ? 1 : 0);
});

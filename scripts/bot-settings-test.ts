import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, rmSync, writeFileSync, readFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { AppDatabase } from "../src/main/db/AppDatabase";
import { ExpertService } from "../src/main/experts/ExpertService";
import { TaskExpertBindingService } from "../src/main/experts/TaskExpertBindingService";
import { BotExpertBindingService } from "../src/main/agent/work/BotExpertBindingService";
import { BotRegistry } from "../src/main/agent/work/BotRegistry";
import { BotSettingsService } from "../src/main/agent/work/BotSettingsService";
import { WorkService, DESKTOP_USER_GRANTS } from "../src/main/agent/work/WorkService";
import { WorkDispatchQueue } from "../src/main/agent/work/WorkDispatchQueue";
import { WorkExecutionAdapter } from "../src/main/agent/work/WorkExecutionAdapter";
import { LOCAL_USER_ID } from "../src/shared/bot-work";

const root = mkdtempSync(join(tmpdir(), "bot-settings-"));
process.env.HOME = root; process.env.USERPROFILE = root;
const db = new AppDatabase(join(root, "app.db"));
const bots = new BotRegistry(db.connection);
const bot = bots.ensureDefaultBot(LOCAL_USER_ID);
const folderA = join(root, "A"), folderB = join(root, "B");
mkdirSync(folderA); mkdirSync(folderB);
const choice = (id: string) => ({ id, name: id, available: true });
const catalog = async () => ({ models: [choice("test/model")], experts: [], skills: [choice("skill")], mcps: [choice("mcp")], connectors: [choice("connector")] });
const skillDir = join(root, "skill-source"); mkdirSync(join(skillDir, "references"), {recursive:true});
writeFileSync(join(skillDir,"SKILL.md"), "---\nname: skill\ndescription: test skill\n---\nRead references/evidence.txt\n");
writeFileSync(join(skillDir,"references","evidence.txt"), "frozen skill evidence");
const experts = new ExpertService();
const taskExperts = new TaskExpertBindingService(db, experts, {rootDir: join(root,"task-experts"), isSkillEnabled: () => true});
const assembly = new BotExpertBindingService(bots, experts, taskExperts, {rootDir:join(root,"bot-experts"),resolveSkillDirectory:id => id === "skill" ? skillDir : undefined});
const service = () => new BotSettingsService(db, bots, LOCAL_USER_ID, join(root, "workspaces"), catalog,
  input => assembly.assembleSettings(input, LOCAL_USER_ID));
const settings = service();
const input = { botId: bot.botId, expectedRevision: 0, workspacePath: folderA, modelId: "test/model", expertId: "", skillIds: ["skill"], mcpIds: ["mcp"], connectorIds: ["connector"] };
try {
  assert.equal(settings.get(bot.botId).revision, 0);
  const saved = await settings.save(input);
  assert.equal(saved.settings.revision, 1);
  assert.deepEqual(bots.activeSnapshot(bot.botId)?.allowedMcpIds, ["mcp"]);
  const frozen = bots.activeSnapshot(bot.botId)!;
  assert.equal(readFileSync(join(frozen.skillPackages![0].directory,"references","evidence.txt"),"utf8"),"frozen skill evidence");
  db.upsertTask({id:"settings-capability-task",title:"mounted capabilities",updatedAt:Date.now()});
  taskExperts.installFrozen("settings-capability-task", frozen.configuration!, frozen.skillPackages!);
  assert.deepEqual(taskExperts.active("settings-capability-task")!.mcpIds,["mcp"]);
  assert.deepEqual(taskExperts.active("settings-capability-task")!.connectorIds,["connector"]);
  assert.equal(readFileSync(join(taskExperts.activeSkillDirectories("settings-capability-task")[0],"references","evidence.txt"),"utf8"),"frozen skill evidence");
  assert.equal(service().get(bot.botId).modelId, "test/model", "settings survive service recreation");
  await assert.rejects(settings.save(input), /已在其他窗口更新/);
  await assert.rejects(settings.save({...input, expectedRevision: 1, modelId: "missing"}), /模型不可用/);
  await assert.rejects(settings.save({...input, expectedRevision: 1, workspacePath: "relative"}), /绝对路径/);
  assert.equal(settings.get(bot.botId).revision, 1);
  assert.throws(() => settings.get("another-bot"), /不属于/);
  const works = new WorkService(db.connection, { bots });
  const made = works.createWork({ kind: "user", userId: LOCAL_USER_ID, entry: "desktop", grants: DESKTOP_USER_GRANTS }, { operationId: "settings-work", title: "task", ownerBotId: bot.botId });
  assert(made.ok);
  const adapter = new WorkExecutionAdapter(works, { prepare: async () => { throw new Error("unused"); }, find: async () => undefined, submit: async () => { throw new Error("unused"); }, inspect: async () => { throw new Error("unused"); }, stop: async () => {} }, LOCAL_USER_ID, () => true, () => {});
  const queue = new WorkDispatchQueue(db, works, adapter, () => true, () => "fallback", () => "default", undefined, work => settings.forWork(work.workId, work.ownerBotId));
  queue.enqueue(made.work, "settings-enqueue");
  const row = db.connection.prepare("SELECT task_id FROM work_dispatch_requests WHERE work_id=?").get(made.work.workId) as {task_id: string};
  const task = db.getTask(row.task_id)!;
  assert.equal(task.modelId, "test/model"); assert.equal(task.spaceId, saved.settings.spaceId);
  assert.equal(settings.taskWorkspace(task.id), folderA);
  await settings.save({...input, expectedRevision: 1, workspacePath: folderB});
  assert.equal(settings.taskWorkspace(task.id), folderA, "changing folder never moves old Work");
  assert.equal(settings.forWork(made.work.workId, bot.botId).effectiveWorkspacePath, folderA);
  const explicit = works.createWork({ kind: "user", userId: LOCAL_USER_ID, entry: "desktop", grants: DESKTOP_USER_GRANTS }, { operationId: "explicit-folder", title: "explicit folder", ownerBotId: bot.botId, workspacePath: folderA });
  assert(explicit.ok);
  assert.equal(settings.forWork(explicit.work.workId, bot.botId, explicit.work.workspacePath).effectiveWorkspacePath, folderA, "explicit Work folder overrides current Bot default B");
  const reset = await settings.save({...input, expectedRevision: 2, workspacePath: ""});
  assert(reset.settings.effectiveWorkspacePath.startsWith(join(root, "workspaces")), "empty restores dedicated default folder");
  assert.equal(db.getSpace(saved.settings.spaceId)?.path, undefined, "space grouping cannot silently migrate running tasks");
  console.log("PASS Bot settings: persistence, isolation, stale save, unavailable capability, real dispatch model/space/cwd, old Work immutability, reset");
} finally { db.close(); rmSync(root, {recursive: true, force: true}); }

import { ExecutionFailureRepository } from "../src/main/agent/ExecutionFailureRepository";
import { prepareTaskWorkspace } from "../src/main/task/prepareTaskWorkspace";
import assert from "node:assert/strict";
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, rmSync, renameSync, symlinkSync, unlinkSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { AppDatabase } from "../src/main/db/AppDatabase";
import { ProjectRepository } from "../src/main/project/ProjectRepository";
import { ProjectService } from "../src/main/project/ProjectService";
import { ArtifactRepository } from "../src/main/artifact/ArtifactRepository";
import { ArtifactService } from "../src/main/artifact/ArtifactService";
import { ArtifactRegistry } from "../src/main/artifact/ArtifactRegistry";
import { ArtifactStorage } from "../src/main/artifact/ArtifactStorage";
import type { ArtifactUpdatedEvent } from "../src/shared/artifact-types";
import { TaskExecutionWorkspace } from "../src/main/task/TaskExecutionWorkspace";
import { resolveTaskWorkspaceCwd } from "../src/main/task/TaskWorkspaceResolver";
import { WorkspacePathError } from "../src/main/workspace/WorkspacePathError";
import { ProjectFolderRelocation } from "../src/main/project/ProjectFolderRelocation";

const root = mkdtempSync(join(tmpdir(), "mybuddy-folder-relocation-"));
const db = new AppDatabase(join(root, "test.db"));
try {
  const oldPath = join(root, "old"); const newPath = join(root, "new");
  mkdirSync(oldPath); writeFileSync(join(oldPath, "spec.txt"), "specification".repeat(6000));
  const repository = new ProjectRepository(db.connection);
  const projects = new ProjectService(repository, {} as any);
  const project = projects.create({ name: "Relocation" });
  db.upsertSpace({ id: "folder", name: "folder", path: oldPath });
  projects.update({ id: project.id, defaultSpaceId: "folder" });
  db.upsertTask({ id: "task", title: "Task", updatedAt: 1, projectId: project.id, spaceId: "folder" });
  const resource = projects.createResource({ projectId: project.id, kind: "file", title: "Spec", value: join(oldPath, "spec.txt") });
  writeFileSync(join(oldPath, "result.html"), "<h1>Result</h1>");
  writeFileSync(join(oldPath, "style.css"), "h1{color:red}");
  const artifactRepository = new ArtifactRepository(db.connection);
  const registry = new ArtifactRegistry();
  const events: ArtifactUpdatedEvent[] = [];
  const artifacts = new ArtifactService(new ArtifactStorage(join(root, "managed")), artifactRepository, registry, { updated: (event) => {
    assert.equal(db.getSpace("folder")?.path, newPath, "Observers see committed bindings");
    assert.equal(db.connection.inTransaction, false, "Publish only after outer commit");
    events.push(event);
  } });
  artifactRepository.insert({ id: "result", taskId: "task", kind: "html", source: { type: "workspace-file", rootDir: oldPath, entryFile: join(oldPath, "result.html") }, version: 1, capabilities: {}, createdAt: 1, updatedAt: 1 });
  artifactRepository.replaceFileDependencies("result", [{ filePath: join(oldPath, "style.css"), dependencyKind: "stylesheet" }]);
  const managedDir = join(root, "managed", "task", "managed-result");
  mkdirSync(managedDir, { recursive: true });
  writeFileSync(join(managedDir, "index.html"), "managed content");
  artifactRepository.insert({ id: "managed-result", taskId: "task", kind: "html", source: { type: "managed-content", rootDir: oldPath, storagePath: "task/managed-result/index.html" }, version: 1, capabilities: {}, createdAt: 2, updatedAt: 2 });
  artifacts.rebuildRegistry();
  const sharedProject = projects.create({ name: "Shared" });
  projects.update({ id: sharedProject.id, defaultSpaceId: "folder" });
  renameSync(oldPath, newPath);
  const failures = new ExecutionFailureRepository(db.connection);
  const workspace = new TaskExecutionWorkspace(join(root, "isolated"));
  assert.throws(() => resolveTaskWorkspaceCwd(db, workspace, "task"), (error: unknown) => error instanceof WorkspacePathError && error.causeCode === "workspace-path-missing" && error.recovery === "requires-user-action");
  assert.throws(() => prepareTaskWorkspace(db, workspace, failures, "task", "assistant-failed"), WorkspacePathError);
  assert.equal(failures.list("task")[0].assistantMessageId, "assistant-failed");
  assert.equal(failures.list("task")[0].resolvedAt, undefined);
  const failedReopen = new AppDatabase(join(root, "test.db"));
  try { assert.equal(new ExecutionFailureRepository(failedReopen.connection).list("task")[0].causeCode, "workspace-path-missing"); } finally { failedReopen.close(); }
  assert.equal(failures.list("other-task").length, 0);
  db.connection.prepare("INSERT INTO execution_failures(id,task_id,cause_code,record_json,created_at) VALUES ('corrupt','task','corrupt','{broken',0)").run();
  assert.equal(failures.list("task").length, 1, "Bad record does not hide intact history");
  assert(db.connection.prepare("SELECT 1 FROM execution_failures WHERE id = 'corrupt'").get(), "Corrupt source retained");
  assert.equal(existsSync(oldPath), false, "Failed execution cannot recreate the moved folder");
  assert.equal(db.getTask("task")?.cwd, undefined, "Failure cannot persist a fallback cwd");
  db.upsertSpace({ id: "invalid", name: "Invalid", path: join(newPath, "spec.txt"), parentId: "folder" });
  db.upsertTask({ id: "invalid-task", title: "Invalid", spaceId: "invalid", updatedAt: 1 });
  assert.throws(() => resolveTaskWorkspaceCwd(db, workspace, "invalid-task"), (error: unknown) => error instanceof WorkspacePathError && error.causeCode === "workspace-path-invalid");
  db.connection.prepare("DELETE FROM tasks WHERE id = 'invalid-task'").run();
  db.connection.prepare("DELETE FROM spaces WHERE id = 'invalid'").run();
  db.upsertTask({ id: "standalone", title: "Standalone", updatedAt: 1 });
  assert.throws(() => db.resolveWorkspaceExecutionPath("unknown-folder", { requireExisting: true }), (error: unknown) => error instanceof WorkspacePathError && error.causeCode === "workspace-binding-missing");
  db.upsertSpace({ id: "relative", name: "Relative", path: "." });
  assert.throws(() => db.resolveWorkspaceExecutionPath("relative", { requireExisting: true }), (error: unknown) => error instanceof WorkspacePathError && error.causeCode === "workspace-path-invalid");
  db.connection.prepare("DELETE FROM spaces WHERE id = 'relative'").run();
  const isolatedCwd = resolveTaskWorkspaceCwd(db, workspace, "standalone");
  assert(existsSync(isolatedCwd), "Unbound tasks still create their isolated workspace");
  let busy = false;
  const service = new ProjectFolderRelocation(db, () => busy, () => artifacts);
  const preview = service.preview(project.id, newPath);
  assert.equal(preview.references[0].oldExists, false);
  assert.equal(preview.artifacts?.length, 2);
  assert.equal(preview.artifacts?.[0].fileCount, 2);
  assert.throws(() => artifacts.applyFolderRelocation([]), /事务/);
  assert.equal(preview.tasks.length, 1);
  assert.equal(db.getSpace("folder")?.path, oldPath, "Preview cannot mutate binding");
  busy = true;
  assert.throws(() => service.commit(preview.token), /执行/);
  busy = false;
  const stale = service.preview(project.id, newPath);
  writeFileSync(join(newPath, "spec.txt"), "changed");
  assert.throws(() => service.commit(stale.token), /发生变化/);
  assert.equal(db.getSpace("folder")?.path, oldPath);
  const rollback = service.preview(project.id, newPath);
  db.connection.exec("CREATE TRIGGER reject_resource_update BEFORE UPDATE ON project_resources BEGIN SELECT RAISE(ABORT, 'injected rollback'); END");
  assert.throws(() => service.commit(rollback.token), /injected rollback/);
  assert.equal(db.getSpace("folder")?.path, oldPath, "Space update rolled back when resource update fails");
  assert.equal(repository.get(project.id)?.resources.find((item) => item.id === resource.id)?.value, join(oldPath, "spec.txt"));
  assert.equal(artifacts.get("result")?.version, 1, "Rolled-back metadata never enters registry");
  assert.equal(artifactRepository.get("result")?.source.rootDir, oldPath);
  assert.equal(artifactRepository.getTaskRevision("task"), 0);
  assert.equal(artifactRepository.listFileDependencies("result")[0].filePath, join(oldPath, "style.css"));
  assert.equal(events.length, 0);
  db.connection.exec("DROP TRIGGER reject_resource_update");
  const artifactStale = service.preview(project.id, newPath);
  writeFileSync(join(newPath, "style.css"), "h1{color:blue}");
  assert.throws(() => service.commit(artifactStale.token), /发生变化/);
  renameSync(join(newPath, "style.css"), join(newPath, "missing.css"));
  assert.throws(() => service.preview(project.id, newPath), /缺少产物/);
  renameSync(join(newPath, "missing.css"), join(newPath, "style.css"));
  db.upsertTask({ id: "foreign", title: "Independent", updatedAt: 1, spaceId: "folder" });
  assert(service.preview(project.id, newPath).tasks.some((task) => task.id === "foreign"));
  db.connection.prepare("DELETE FROM tasks WHERE id = 'foreign'").run();
  artifactRepository.insert({ id: "foreign-artifact", taskId: "independent", kind: "html", source: { type: "workspace-file", rootDir: oldPath, entryFile: join(oldPath, "result.html") }, version: 1, capabilities: {}, createdAt: 1, updatedAt: 1 });
  assert.throws(() => service.preview(project.id, newPath), /其他任务的产物/);
  artifactRepository.remove("foreign-artifact");
  mkdirSync(oldPath);
  writeFileSync(join(oldPath, "result.html"), "different original");
  assert.throws(() => service.preview(project.id, newPath), /新旧产物内容不一致/);
  rmSync(oldPath, { recursive: true });
  const outside = join(root, "outside");
  mkdirSync(outside); writeFileSync(join(outside, "asset.css"), "external");
  symlinkSync(outside, join(newPath, "escape"), "junction");
  artifactRepository.replaceFileDependencies("result", [{ filePath: join(oldPath, "escape", "asset.css") }]);
  assert.throws(() => service.preview(project.id, newPath), /越界/);
  unlinkSync(join(newPath, "escape"));
  artifactRepository.replaceFileDependencies("result", [{ filePath: join(oldPath, "style.css"), dependencyKind: "stylesheet" }]);
  mkdirSync(join(newPath, "nested"));
  db.upsertSpace({ id: "nested", name: "Nested", path: join(oldPath, "nested"), parentId: "folder" });
  db.upsertSpace({ id: "virtual", name: "Inherited", parentId: "nested" });
  db.upsertSpace({ id: "unmoved", name: "Outside", path: outside, parentId: "folder" });
  const sharedRef = projects.createResource({ projectId: sharedProject.id, kind: "file", title: "Shared spec", value: join(oldPath, "spec.txt") });
  db.upsertTask({ id: "inherited", title: "Inherited task", updatedAt: 1, spaceId: "virtual", projectId: sharedProject.id });
  db.upsertTask({ id: "independent", title: "Independent shared task", updatedAt: 1, spaceId: "folder" });
  db.upsertTask({ id: "unmoved-task", title: "Outside task", updatedAt: 1, spaceId: "unmoved", projectId: sharedProject.id });
  assert.throws(() => resolveTaskWorkspaceCwd(db, workspace, "inherited"), (error: unknown) => error instanceof WorkspacePathError && error.causeCode === "workspace-path-missing");
  const changedScope = service.preview(project.id, newPath);
  assert.equal(changedScope.folders?.length, 2);
  assert.equal(changedScope.affectedProjects?.length, 2);
  assert(changedScope.tasks.some((task) => task.id === "inherited"));
  assert(changedScope.tasks.some((task) => task.id === "independent"));
  assert(!changedScope.tasks.some((task) => task.id === "unmoved-task"));
  db.upsertTask({ id: "late", title: "Added after preview", updatedAt: 1, spaceId: "virtual" });
  assert.throws(() => service.commit(changedScope.token), /发生变化/);
  const onlyInheritedBusy = new ProjectFolderRelocation(db, (id) => id === "inherited", () => artifacts);
  assert.throws(() => onlyInheritedBusy.preview(project.id, newPath), /执行/);
  const sharedRollback = service.preview(project.id, newPath);
  db.connection.exec(`CREATE TRIGGER reject_shared_resource BEFORE UPDATE ON project_resources WHEN OLD.id = '${sharedRef.id}' BEGIN SELECT RAISE(ABORT, 'shared rollback'); END`);
  assert.throws(() => service.commit(sharedRollback.token), /shared rollback/);
  assert.equal(db.getSpace("nested")?.path, join(oldPath, "nested"));
  assert.equal(db.getSpace("folder")?.path, oldPath);
  assert.equal(events.length, 0);
  db.connection.exec("DROP TRIGGER reject_shared_resource");
  const approved = service.preview(project.id, newPath);
  service.commit(approved.token);
  assert.equal(db.getSpace("folder")?.path, newPath);
  assert.equal(db.getSpace("nested")?.path, join(newPath, "nested"));
  assert.equal(db.getSpace("nested")?.parentId, "folder");
  assert.equal(resolveTaskWorkspaceCwd(db, workspace, "inherited"), join(newPath, "nested"));
  assert.equal(prepareTaskWorkspace(db, workspace, failures, "task", "assistant-retry"), newPath);
  assert(failures.list("task")[0].resolvedAt, "Actual preflight success resolves the prior path failure");
  assert.equal(existsSync(oldPath), false, "Recovered execution uses the new folder");
  assert.equal(db.getSpace("unmoved")?.path, outside);
  assert.equal(db.resolveWorkspaceExecutionPath("virtual"), join(newPath, "nested"));
  assert.equal(repository.get(sharedProject.id)?.resources[0].value, join(newPath, "spec.txt"));
  assert.equal(repository.get(project.id)?.resources[0].value, join(newPath, "spec.txt"));
  assert.equal(db.getTask("task")?.spaceId, "folder");
  assert.equal(db.getTask("task")?.projectId, project.id);
  assert.equal(readFileSync(join(newPath, "spec.txt"), "utf8"), "changed");
  assert.throws(() => service.commit(approved.token), /失效/);
  assert.equal(artifacts.get("result")?.source.rootDir, newPath);
  assert.equal(artifacts.entryPathOf("result"), join(newPath, "result.html"));
  assert.equal(artifacts.get("result")?.version, 2);
  assert.equal(events.length, 2);
  assert.equal(artifacts.entryPathOf("managed-result"), join(managedDir, "index.html"));
  assert.equal(readFileSync(join(managedDir, "index.html"), "utf8"), "managed content");
  assert.equal(artifacts.get("managed-result")?.source.rootDir, newPath);
  assert.equal(events[0].revision, 1);
  assert.equal(artifactRepository.listFileDependencies("result")[0].filePath, join(newPath, "style.css"));
  const reopened = new AppDatabase(join(root, "test.db"));
  try { assert.equal(new ArtifactRepository(reopened.connection).get("result")?.source.rootDir, newPath); } finally { reopened.close(); }
  console.log("project folder relocation: PASS (preview, moved folder, busy, stale content, shared binding, transactional rollback, artifact cache/events/dependencies, managed storage, junction escape, restart, commit)");
} finally { db.close(); rmSync(root, { recursive: true, force: true }); }

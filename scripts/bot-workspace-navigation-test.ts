import assert from 'node:assert/strict';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {AppDatabase} from '../src/main/db/AppDatabase';
import {BotRegistry} from '../src/main/agent/work/BotRegistry';
import {WorkService,DESKTOP_USER_GRANTS} from '../src/main/agent/work/WorkService';
import {BotConversationRepository} from '../src/main/agent/work/BotConversationRepository';
import {BotWorkspaceNavigationService,botWorkspaceSpaceId,teamWorkspaceSpaceId} from '../src/main/agent/work/BotWorkspaceNavigationService';
import {LOCAL_USER_ID} from '../src/shared/bot-work';
const root=mkdtempSync(join(tmpdir(),'bot-workspace-nav-'));
const db=new AppDatabase(join(root,'app.db'));
try {
 const bots=new BotRegistry(db.connection), bot=bots.ensureDefaultBot(LOCAL_USER_ID);
 const works=new WorkService(db.connection,{bots});
 const service=new BotWorkspaceNavigationService(db,LOCAL_USER_ID);
 db.upsertSpace({id:'user-bot',name:'Bot'});
 const legacy=botWorkspaceSpaceId(bot.botId);
 db.upsertSpace({id:legacy,name:`${bot.displayName} · 工作空间`,path:'/unchanged/path'});
 const messages=new BotConversationRepository(db.connection);
 const sent=messages.accept(LOCAL_USER_ID,{botId:bot.botId,requestId:'personal',text:'天气如何'});
 messages.update(sent.assistantMessageId,'completed','晴');
 db.connection.prepare('UPDATE bot_conversations SET archived_at=10 WHERE conversation_id=?').run(sent.conversationId);
 db.connection.prepare('INSERT INTO work_team_templates VALUES (?,?,?,?,?,?,?,NULL)').run('team-one',LOCAL_USER_ID,'op','hash','团队一','{}',1);
 const teamSent=messages.accept(LOCAL_USER_ID,{botId:bot.botId,teamId:'team-one',requestId:'team',text:'完成团队任务'});
 const made=works.createWork({kind:'user',userId:LOCAL_USER_ID,entry:'desktop',grants:DESKTOP_USER_GRANTS},{operationId:'w',title:'团队后台',ownerBotId:bot.botId}); assert(made.ok);
 db.connection.prepare('INSERT INTO work_teams VALUES (?,?,?,?,?,?,?,?)').run(made.work.workId,LOCAL_USER_ID,'op2','hash','{}',1,'snapshot',1);
 db.connection.prepare('INSERT INTO work_team_ownership VALUES (?,?,?)').run(made.work.workId,'team-one','团队一');
 db.upsertTask({id:'native-task',title:'工作',cwd:'/original/running/cwd',spaceId:legacy,updatedAt:1});
 // Actual dispatch schema is initialized by WorkService; use only its required fields.
 db.connection.prepare(`INSERT INTO work_dispatch_requests(work_id,operation_id,task_id,state,created_at,bot_id,intent_revision,input_snapshot_id) VALUES (?,?,?,'pending',?,?,?,?)`).run(made.work.workId,'op-native','native-task',1,bot.botId,1,'snapshot');
 const beforeTasks=db.listTasks().length;
 const snap=service.snapshot();
 assert.equal(snap.foregroundRequests.length,2);
 assert.equal(snap.foregroundRequests.find(r=>r.requestId==='personal')?.archived,true);
 assert.equal(snap.foregroundRequests.find(r=>r.requestId==='personal')?.status,'completed');
 assert.equal(snap.foregroundRequests.find(r=>r.requestId==='team')?.spaceId,teamWorkspaceSpaceId('team-one'));
 assert.equal(snap.foregroundRequests.find(r=>r.requestId==='team')?.messageId,teamSent.assistantMessageId);
 assert.equal(db.getTask('native-task')?.spaceId,teamWorkspaceSpaceId('team-one'));
 assert.equal(db.getTask('native-task')?.cwd,'/original/running/cwd');
 assert.equal(db.getSpace(legacy)?.path,'/unchanged/path');
 assert.equal(db.listTasks().length,beforeTasks,'foreground never creates executable Tasks');
 assert.notEqual(db.getSpace(legacy)?.parentId,'user-bot','same-name user folder is never adopted');
 db.renameSpace(legacy,'我自己的名称');
 db.connection.prepare('UPDATE spaces SET parent_id=NULL WHERE id=?').run(legacy);
 service.snapshot();assert.equal(db.getSpace(legacy)?.name,'我自己的名称');assert.equal(db.getSpace(legacy)?.parentId,null);
 db.connection.prepare('UPDATE work_team_templates SET name=? WHERE template_id=?').run('团队新名字','team-one');
 service.snapshot();assert.equal(db.getSpace(teamWorkspaceSpaceId('team-one'))?.name,'团队新名字 · 工作空间');
 assert.equal(new BotWorkspaceNavigationService(db,'another-user').snapshot().foregroundRequests.length,0);
 console.log('PASS workspace hierarchy: identity, collision, rename/move, completed/archived foreground, team-only native assignment, cwd preserved, no Task synthesis, user isolation');
} finally {db.close();rmSync(root,{recursive:true,force:true});}

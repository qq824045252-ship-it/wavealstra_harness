const { app, BrowserWindow } = require('electron');
const { writeScreenshot, settleFramesScript } = require('./ui-capture.cjs');
const { mkdirSync, writeFileSync } = require('node:fs');
const { join } = require('node:path');
const assert = require('node:assert/strict');
const output = join(__dirname, '../out/tests');
app.setPath('userData', join(output, 'project-materials-profile'));
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 1240, height: 850, webPreferences: { sandbox: true, contextIsolation: true, backgroundThrottling: false } });
  const evaluate = async (code) => { try { return await win.webContents.executeJavaScript(code); } catch (error) { console.error('[project-materials-ui] evaluate failed:', code); throw error; } };
  const wait = async (code) => {
    const deadline = Date.now() + 5000;
    while (!(await evaluate(code))) {
      if (Date.now() > deadline) throw new Error(`UI wait timed out: ${code}`);
      await new Promise((accept) => setTimeout(accept, 50));
    }
  };
  const click = async (label) => {
    await evaluate(`(()=>{const b=[...document.querySelectorAll('button')].find(b=>b.textContent.trim()===${JSON.stringify(label)} && b.getClientRects().length); if(!b || b.disabled)throw Error('button unavailable'); b.click()})()`);
  };
  const visibleText = `document.body.innerText`;
  const capture = async (name) => {
    await evaluate(settleFramesScript);
    await new Promise((accept) => setTimeout(accept, 100));
    await writeScreenshot(win, join(output, name));
  };
  try {
    mkdirSync(output, { recursive: true });
    const html = join(output, 'project-materials-ui.html');
    writeFileSync(html, '<!doctype html><html lang="zh"><meta charset="UTF-8"><link rel="stylesheet" href="project-materials-ui.css"><div id="root"></div><script src="project-materials-ui.js"></script></html>');
    await win.loadFile(html);
    await wait(`document.body.innerText.includes('还没有项目资料')`);
    await wait(`document.querySelector('[aria-label="资料状态"]').innerText.includes('1/1')`);
    assert((await evaluate(`document.querySelector('[aria-label="资料状态"]').innerText`)).includes('未查看'), '没有选执行记录时不得暗示资料已被使用');
    await evaluate(`(()=>{const input=document.querySelector('input[aria-label="搜索项目资料"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'写作规范');input.dispatchEvent(new Event('input',{bubbles:true}))})()`);
    await wait(`document.body.innerText.includes('没有匹配的项目资料') && document.body.innerText.includes('写作规范')`);
    assert.equal(await evaluate(`document.querySelectorAll('input[aria-label="搜索文件或文件夹"]').length`), 0, '统一资料页不应再暴露第二个内部搜索框');
    await click('清除搜索');
    await wait(`document.querySelector('input[aria-label="搜索项目资料"]').value === ''`);
    await evaluate(`(()=>{const s=[...document.querySelectorAll('summary')].find(s=>s.textContent==='项目说明');s.click()})()`);
    await evaluate(`(()=>{const s=document.querySelector('textarea[aria-label="项目目标"]');Object.getOwnPropertyDescriptor(HTMLTextAreaElement.prototype,'value').set.call(s,'验证项目长期目标');s.dispatchEvent(new Event('input',{bubbles:true}))})()`);
    await wait(`window.materialTest.guard?.dirty === true`);
    await click('保存项目说明');
    await wait(`window.materialTest.guard?.dirty === false`);
    assert.equal(await evaluate(`window.materialTest.calls.find(c=>c[0]==='updateProject')[1].goal`), '验证项目长期目标');
    await evaluate(`(()=>{const s=document.querySelector('input[aria-label="当前阶段"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(s,'等待确认');s.dispatchEvent(new Event('input',{bubbles:true}));window.materialTest.failNextSave()})()`);
    await click('保存项目说明');
    await wait(`document.body.innerText.includes('模拟项目说明保存失败')`);
    assert.equal(await evaluate(`document.querySelector('input[aria-label="当前阶段"]').value`), '等待确认');
    assert.equal(await evaluate(`window.materialTest.guard.dirty`), true);
    await click('撤销修改');
    await wait(`window.materialTest.guard?.dirty === false`);
    await capture('project-brief.png');
    await evaluate(`(()=>{const s=[...document.querySelectorAll('summary')].find(s=>s.textContent==='项目说明');s.click()})()`);
    await evaluate(`(()=>{const s=document.querySelector('select[aria-label="项目工作目录"]');s.value='folder-a';s.dispatchEvent(new Event('change',{bubbles:true}))})()`);
    await wait(`document.body.innerText.includes('C:/projects/a。')`);
    assert.equal(await evaluate(`window.materialTest.calls.find(c=>c[0]==='updateProject' && c[1].defaultSpaceId)[1].defaultSpaceId`), 'folder-a');
    await click('文件夹已移动？重新关联');
    await wait(`!!document.querySelector('[aria-label="确认重新关联项目目录"]')`);
    assert.equal(await evaluate(`window.materialTest.calls.filter(c=>c[0]==='commitFolder').length`), 0);
    assert((await evaluate(visibleText)).includes('1 个产物及其依赖'));
    assert((await evaluate(visibleText)).includes('共享设计'));
    await evaluate(`(()=>{const s=[...document.querySelectorAll('summary')].find(s=>s.textContent==='查看 2 个文件夹的位置变化');s.click()})()`);
    assert((await evaluate(visibleText)).includes('C:/moved/a/nested'));
    await evaluate(`(()=>{const s=[...document.querySelectorAll('summary')].find(s=>s.textContent==='查看受影响产物');s.click()})()`);
    assert((await evaluate(visibleText)).includes('项目报告'));
    assert((await evaluate(visibleText)).includes('部分原文件已不存在'));
    await capture('project-folder-relocation.png');
    await click('取消');
    assert.equal(await evaluate(`window.materialTest.calls.filter(c=>c[0]==='commitFolder').length`), 0);
    await evaluate(`window.materialTest.failNextRelocation()`);
    await click('文件夹已移动？重新关联');
    await wait(`!!document.querySelector('[aria-label="确认重新关联项目目录"]')`);
    await click('确认重新关联');
    await wait(`document.body.innerText.includes('模拟目录提交失败，绑定未修改')`);
    assert((await evaluate(visibleText)).includes('C:/projects/a。'));
    await click('文件夹已移动？重新关联');
    await wait(`!!document.querySelector('[aria-label="确认重新关联项目目录"]')`);
    await click('确认重新关联');
    await wait(`document.body.innerText.includes('已重新关联目录和文件引用')`);
    assert.equal(await evaluate(`window.materialTest.calls.filter(c=>c[0]==='commitFolder').length`), 1);
    await evaluate(`(()=>{const s=[...document.querySelectorAll('summary')].find(s=>s.textContent==='本次实际使用资料');s.click()})()`);
    assert(!(await evaluate(visibleText)).includes('其他项目任务'));
    await evaluate(`(()=>{const s=document.querySelector('select[aria-label="查看资料使用的任务"]');s.value='task-a';s.dispatchEvent(new Event('change',{bubbles:true}))})()`);
    await wait(`document.body.innerText.includes('实际执行目录：C:/actual/run-a')`);
    await wait(`document.querySelector('[aria-label="资料状态"]').innerText.includes('读取证据 3 · 注入 1 · 另 1 项未保留')`);
    assert((await evaluate(visibleText)).includes('文件返回内容 · requirements.md'));
    assert((await evaluate(visibleText)).includes('检索片段 · 技术规范'));
    assert((await evaluate(visibleText)).includes('仅元数据／链接 · 设计图.pdf'));
    assert((await evaluate(visibleText)).includes('另有 1 项未保留'));
    assert.equal(await evaluate(`document.querySelector('select[aria-label="选择执行记录"]').options.length`), 1);
    await evaluate(`(()=>{const s=[...document.querySelectorAll('summary')].find(s=>s.textContent.includes('补充参考正文'));s.click()})()`);
    await wait(`document.body.innerText.includes('实际注入的写作规范')`);
    await capture('project-execution-materials.png');
    await evaluate(`(()=>{const s=document.querySelector('select[aria-label="查看资料使用的任务"]');s.value='task-empty';s.dispatchEvent(new Event('change',{bubbles:true}))})()`);
    await wait(`document.body.innerText.includes('暂无该项目下的执行记录')`);
    assert(!(await evaluate(visibleText)).includes('实际注入的写作规范'));
    await evaluate(`(()=>{const s=[...document.querySelectorAll('summary')].find(s=>s.textContent==='本次实际使用资料');s.click()})()`);
    assert(!(await evaluate(visibleText)).includes('个人私有资料'));
    assert(!(await evaluate(visibleText)).includes('设备检查单'));
    await click('导入文档');
    await wait(`document.body.innerText.includes('已导入 1 个文档')`);
    await wait(`document.querySelector('[aria-label="资料状态"]').innerText.includes('项目资料') && document.querySelector('[aria-label="资料状态"]').innerText.includes('1')`);
    assert.deepEqual(await evaluate(`window.materialTest.calls.filter(c=>c[0]==='create').map(c=>c[1].projectId)`), ['a']);
    await capture('project-materials-after.png');
    await evaluate(`(()=>{const input=document.querySelector('input[aria-label="搜索项目资料"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'不存在的资料');input.dispatchEvent(new Event('input',{bubbles:true}))})()`);
    await wait(`document.body.innerText.includes('没有匹配的项目资料')`);
    await evaluate(`(()=>{const input=document.querySelector('input[aria-label="搜索项目资料"]');Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(input,'');input.dispatchEvent(new Event('input',{bubbles:true}))})()`);
    await wait(`document.body.innerText.includes('项目说明')`);
    await click('查看');
    await wait(`document.body.innerText.includes('这是当前项目的长期文档')`);
    await evaluate(`window.materialTest.failNextPin()`);
    await click('设为常用资料');
    await wait(`document.body.innerText.includes('模拟常用资料保存失败')`);
    assert((await evaluate(visibleText)).includes('常用资料 · 0/10'));
    await click('设为常用资料');
    await wait(`document.body.innerText.includes('常用资料 · 1/10')`);
    await capture('project-common-materials.png');
    assert.equal(await evaluate(`window.materialTest.calls.find(c=>c[0]==='pin')[1].projectId`), 'a');
    await click('取消常用');
    await wait(`document.body.innerText.includes('已取消常用，原文档保留')`);
    assert((await evaluate(visibleText)).includes('这是当前项目的长期文档'));
    await capture('project-materials-document.png');
    await click('返回文档列表');
    await wait(`document.body.innerText.includes('写作规范')`);
    assert(!(await evaluate(visibleText)).includes('打开资料库'));
    await evaluate(`window.materialTest.addSecondSpace()`);
    await click('刷新');
    await wait(`!!document.querySelector('select[aria-label="导入位置"]')`);
    await click('导入文档');
    await wait(`document.body.innerText.includes('请选择本项目的导入位置')`);
    assert.equal(await evaluate(`window.materialTest.calls.filter(c=>c[0]==='import').length`), 1);
    await evaluate(`(()=>{const s=document.querySelector('select[aria-label="导入位置"]');s.value='a-second';s.dispatchEvent(new Event('change',{bubbles:true}));window.materialTest.failImport()})()`);
    await click('导入文档');
    await wait(`document.body.innerText.includes('模拟导入失败')`);
    await evaluate(`window.materialTest.deferNextSnapshot()`);
    await click('刷新');
    await evaluate(`window.materialTest.switchProject('b')`);
    await wait(`document.body.innerText.includes('设备检查单')`);
    await evaluate(`window.materialTest.releaseSnapshot()`);
    await new Promise((accept) => setTimeout(accept, 100));
    assert(!(await evaluate(`document.querySelector('[aria-label="项目资料"]').innerText`)).includes('项目说明'));
    assert((await evaluate(visibleText)).includes('设备检查单'));
    await evaluate(`window.materialTest.showTaskModal()`);
    await wait(`!!document.querySelector('.project-task-modal')`);
    await wait(`document.querySelector('.project-task-modal select').value==='folder-a'`);
    await click('创建任务');
    assert.equal(await evaluate(`window.createdProjectTask.spaceId`), 'folder-a');
    await evaluate(`(()=>{const s=document.querySelector('.project-task-modal select');s.value='';s.dispatchEvent(new Event('change',{bubbles:true}))})()`);
    await click('创建任务');
    assert.equal(await evaluate(`window.createdProjectTask.spaceId`), undefined);
    await evaluate(`window.materialTest.showRecovery('task-recovery')`);
    await wait(`document.body.innerText.includes('需要处理')`);
    await click('打开项目资料');
    assert.deepEqual(await evaluate(`window.openedRecoveryProject`), ['a', 'assets']);
    await capture('task-recovery-notice.png');
    await evaluate(`window.materialTest.showRecovery('task-recovery', true)`);
    await wait(`!document.querySelector('[aria-label="任务恢复"]')`);
    console.log('project materials Electron UI: PASS (folder default and override, execution materials and empty state, import, read, scope, errors, stale project response)');
    app.quit();
  } catch (error) { console.error(error); app.exit(1); }
});

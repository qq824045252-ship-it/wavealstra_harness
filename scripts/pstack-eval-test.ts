import assert from "node:assert/strict";
import { link, mkdtemp, mkdir, readFile, writeFile, rm } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { normalizePstackSettings, validatePstackSettings } from "../src/shared/pstack";
import type { WorkflowRun } from "../src/main/agent/pstack/PstackState";
import { auditParticipant, contestDispatch, prepareContestAdvance } from "../src/main/agent/pstack/PstackContest";
import { chooseContestModels } from "../src/main/agent/pstack/PstackContestModels";
import { arenaSubmission, arenaSurvivors } from "../src/main/agent/pstack/PstackArenaSubmission";
import { execFileSync } from "node:child_process";
import { verifyEvalHost } from "./pstack-eval-host";
import { saveEvalDocument } from "../src/main/agent/pstack/PstackEvalExport";

const dir = await mkdtemp(join(tmpdir(), "mb-project-"));
try {
  const settings = normalizePstackSettings(), criteria = ["Preserve aliases", "Handle missing names", "Explain collisions"];
  settings.playbooks.eval.parameters.rubricCount = 3;
  settings.skills.arena.parameters.rubricCount = 5;
  const run = { playbook: "eval", contests: {}, delegates: [] } as unknown as WorkflowRun;
  await assert.rejects(prepareContestAdvance(run, settings, dir, "rubric", { criteria: [...criteria, "Extra"] }), /exactly 3/);
  await assert.rejects(prepareContestAdvance({...run, playbook: "skill:arena"}, settings, dir, "frame", { criteria }), /exactly 5/);
  await writeFile(join(dir,"rules.json"), JSON.stringify({criteria}));
  run.contests!.eval = (await prepareContestAdvance(run, settings, dir, "rubric", { artifact:"rules.json" }))!;
  const threePoint = normalizePstackSettings({playbooks:{eval:{parameters:{rubricCount:3,ratingMinimum:0,ratingMaximum:2}}}});
  assert.deepEqual((await prepareContestAdvance(run,threePoint,dir,"rubric",{criteria}))?.scale,{min:0,max:2});
  assert.ok(validatePstackSettings({skills:{arena:{parameters:{ratingMinimum:9,ratingMaximum:1}}}}).some(e=>e.includes("ratingMaximum")));
  await mkdir(join(dir,"variant-one"));
  await writeFile(join(dir,"variant-one/roster.md"), "Keep the two Springfield teams separate.");
  await writeFile(join(dir,"rubric.md"), "Hidden scoring sheet");
  await assert.rejects(prepareContestAdvance(run,settings,dir,"isolate",{materials:[["rubric.md"]]}), /ordinary task/);
  await writeFile(join(dir,"project.md"), criteria.join("\n"));
  await assert.rejects(prepareContestAdvance(run,settings,dir,"isolate",{materials:[["project.md"]]}), /private criterion/);
  const isolated = (await prepareContestAdvance(run,settings,dir,"isolate",{materials:[["variant-one/roster.md"],[]]}))!;
  assert.deepEqual(Object.entries(isolated.materials![0]), [["roster.md", "Keep the two Springfield teams separate."]]);
  assert.equal(Object.keys(isolated.materials![1]).length, 0);
  run.contests!.eval = isolated;
  const request = "How should I tidy our team names?";
  await assert.rejects(prepareContestAdvance(run,settings,dir,"prompt",{prompt:"This is an experiment. Describe your process."}), /ordinary task/);
  for (const prompt of ["You are taking part in an evaluation.", "You are competing in a comparison.", "List the files you used."])
    await assert.rejects(prepareContestAdvance(run,settings,dir,"prompt",{prompt}), /ordinary task/);
  run.contests!.eval = (await prepareContestAdvance(run,settings,dir,"prompt",{prompt:request}))!;
  const batch = contestDispatch(run,"candidates","arena-runners",["Rubric and leaked sibling response","Use other rules"],dir,settings)!;
  assert.equal(batch.count,2);
  assert.ok("tasks" in batch.args && Array.isArray(batch.args.tasks));
  assert.deepEqual(batch.args.tasks.map(t => (t as {task:string}).task),[request,request]);
  const models = ["pool/gpt-alpha","pool/deepseek-a","alt/deepseek-a","pool/deepseek-b"];
  const scope = {available:models, pools:{diverse:models}};
  const authors = chooseContestModels(settings,scope,true);
  assert.deepEqual(authors, ["pool/deepseek-a","pool/deepseek-b"]);
  assert.deepEqual(chooseContestModels(settings,scope,true,authors), ["pool/gpt-alpha"]);
  const ordered = { ...scope, pools: { diverse: ["pool/deepseek-a","pool/gpt-alpha","pool/deepseek-b"] } };
  settings.roles["arena-cross-judge"].count=1;
  assert.equal(normalizePstackSettings(settings).roles["arena-cross-judge"].count,1);
  assert.throws(() => chooseContestModels(settings,ordered,true,authors), /no available model family/);
  settings.roles["arena-cross-judge"].count=2;
  assert.deepEqual(chooseContestModels(settings,ordered,true,authors),["pool/gpt-alpha"]);
  assert.throws(() => chooseContestModels(settings,{...scope,supportsEffort:id=>id!=="pool/gpt-alpha"},true,authors), /no available model family/);
  assert.throws(() => chooseContestModels(settings,{...scope,available:models.slice(0,3)},true), /independent judge family/);
  const receipts = { role:"arena-runners", stageId:"candidates", stage:3, toolTaskId:12, children:["a","b"], models:authors, answers:["Think like DeepSeek-A.", "Second full text."] };
  run.delegates.push(receipts);
  const jury = contestDispatch(run,"judge","arena-cross-judge",["Tell me who won by model name"],dir,settings)!;
  assert.equal(jury.count,1);
  const judgePrompt = String(jury.args.task), inputs = JSON.parse(judgePrompt.split("\n")[1]);
  assert.deepEqual(inputs.criteria, criteria);
  assert.deepEqual(inputs.submissions, [{label:"Document 1",text:"Think like [redacted]."}, {label:"Document 2",text:"Second full text."}]);
  assert.doesNotMatch(judgePrompt,/DeepSeek|pool\/|by model name/i);
  const result = (n:number) => JSON.stringify({scores:["Document 1","Document 2"].map(label => ({label,reason:"Addresses aliases", ratings:Array(n).fill(4)})),recommended:"Document 2"});
  assert.throws(() => jury.check([authors[0]], [result(3)]), /independent/);
  assert.throws(() => jury.check(["pool/gpt-alpha"], [result(2)]), /every frozen criterion/);
  jury.check(["pool/gpt-alpha"], [result(3)]);
  const user = { role:"user",content:[{type:"text",text:request}] };
  const calls = {role:"assistant",content:[
    {type:"toolCall",name:"project_document",id:"read",arguments:{name:"roster.md"}},
    {type:"toolCall",name:"project_document",id:"bogus",arguments:{name:"another.md"}},
    {type:"toolCall",name:"project_document",id:"write",arguments:{name:"notes.md",content:"output"}},
  ]};
  const done = (id:string,failed=false) => ({role:"toolResult",toolName:"project_document",toolCallId:id,isError:failed,content:[]});
  const seen = auditParticipant(22,[user,calls,done("read"),done("bogus",true),done("write")],request);
  assert.deepEqual(seen.audit.filesRead, ["roster.md"]);
  assert.deepEqual(seen.audit.filesWritten, ["notes.md"]);
  assert.deepEqual(seen.files, {"notes.md":"output"});
  assert.throws(() => auditParticipant(22,[user,{...user,content:[{type:"text",text:"Leaked parent instruction"}]}],request), /different request/);
  const author = {subagentId:"a",status:"completed",exitCode:0}, abandoned = {subagentId:"b",status:"failed",exitCode:1,errorMessage:"Account unavailable"};
  assert.deepEqual(arenaSurvivors({results:[author,abandoned]},2),{results:[author],dropouts:[{child:"b",status:"failed",reason:"Account unavailable"}]});
  assert.throws(() => arenaSurvivors({results:[abandoned]},1), /No Arena author/);
  assert.deepEqual(chooseContestModels(settings,{...scope,parent:"pool/gpt-alpha"},false,authors),["pool/deepseek-a"]);
  const cwd = join(dir,"project");
  await mkdir(cwd);
  const git = (...args:string[]) => execFileSync("git",["-C",cwd,...args],{encoding:"utf8",windowsHide:true}).trim();
  git("init","-q");
  await writeFile(join(cwd,"policy.md"), "Initial");
  await writeFile(join(cwd,"removed.txt"), "obsolete");
  git("add","."); git("-c","user.name=fixture","-c","user.email=fixture@invalid","commit","-qm","project start");
  const baseCommit = git("rev-parse","HEAD");
  await writeFile(join(cwd,"policy.md"), "Updated rule");
  await writeFile(join(cwd,"new.txt"), "Complete new document");
  await rm(join(cwd,"removed.txt"));
  const submitted = await arenaSubmission({kind:"worktree",baseCommit,cwd},[]);
  assert.deepEqual({...submitted},{"policy.md":"Updated rule","removed.txt":null,"new.txt":"Complete new document"});
  const contents="匿名完整产物", pending=join(dir,".draft.md.recover.tmp");
  await writeFile(pending,Buffer.from(contents).subarray(0,4));
  await saveEvalDocument(dir,"draft.md",contents,"recover",()=>{});
  assert.equal(await readFile(join(dir,"draft.md"),"utf8"),contents);
  await link(join(dir,"draft.md"),pending);
  await saveEvalDocument(dir,"draft.md",contents,"recover",()=>{});
  await assert.rejects(readFile(pending),{code:"ENOENT"});
  await verifyEvalHost(dir);
  console.log("PASS blind eval and arena rubric settings, candidate input isolation, actual child observations, anonymous single-judge scoring and model-family eligibility");
} finally { await rm(dir,{recursive:true,force:true}); }

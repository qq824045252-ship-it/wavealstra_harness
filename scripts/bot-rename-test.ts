import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { AppDatabase } from "../src/main/db/AppDatabase";
import { BotRegistry } from "../src/main/agent/work/BotRegistry";
import { BotCreationService } from "../src/main/agent/work/BotCreationService";
import { WorkService, DESKTOP_USER_GRANTS } from "../src/main/agent/work/WorkService";
import { LOCAL_USER_ID } from "../src/shared/bot-work";
const root = mkdtempSync(join(tmpdir(), "bot-rename-"));
const file = join(root, "app.db");
let db = new AppDatabase(file);
let bots = new BotRegistry(db.connection);
let service = new BotCreationService(db.connection, bots, { userId: LOCAL_USER_ID, isAuthority: () => true });
const bot = bots.registerBot({ botId: "rename-test", userId: LOCAL_USER_ID, displayName: "原名称", authorization: DESKTOP_USER_GRANTS });
bots.registerBot({ botId: "other", userId: LOCAL_USER_ID, displayName: "Already Used" });
bots.registerBot({ botId: "foreign", userId: "other-user", displayName: "Foreign" });
const works = new WorkService(db.connection, { bots });
const created = works.createWork({ kind: "user", userId: LOCAL_USER_ID, grants: DESKTOP_USER_GRANTS }, {operationId: "create", title: "保留的任务", ownerBotId: bot.botId, authorization: DESKTOP_USER_GRANTS, inputSnapshotId: "input"});
assert(created.ok);
const spaceId = "bot-space-" + createHash("sha256").update(bot.botId).digest("hex").slice(0,24);
db.upsertSpace({ id: spaceId, name: "原名称 · 工作空间" });
const conversation = db.connection.prepare("SELECT conversation_id FROM bot_conversations WHERE bot_id=?").get(bot.botId) as {conversation_id:string};
assert(conversation);
const rename = (displayName: string, expectedUpdatedAt = bots.getBot(bot.botId)!.updatedAt) => service.renameBot({ botId: bot.botId, expectedUpdatedAt, displayName });
for (const name of ["", "  ", "x".repeat(81), "bad\nname", "Ａｌｒｅａｄｙ Ｕｓｅｄ"]) assert.equal(rename(name).ok, false, name);
assert.equal(service.renameBot({botId:"foreign",expectedUpdatedAt:0,displayName:"Foreign2"}).ok,false);
const result = rename("  新名称  ");
assert(result.ok); assert.equal(result.bot.displayName,"新名称");
assert.deepEqual(result.bot.authorization,bot.authorization);
assert.deepEqual(result.bot.expertProfile,bot.expertProfile);
assert.deepEqual(result.bot.memoryScope,bot.memoryScope);
assert.equal(works.getWork(created.work.workId)!.ownerBotId,bot.botId);
assert.equal(db.getSpace(spaceId)!.name,"新名称 · 工作空间");
assert.equal((db.connection.prepare("SELECT bot_id FROM bot_conversations WHERE conversation_id=?").get(conversation.conversation_id) as {bot_id:string}).bot_id,bot.botId);
assert.equal(rename("不应覆盖",bot.updatedAt).ok,false);
assert.equal(rename("新名称",bot.updatedAt).ok,true,"safe response-loss replay");
db.close(); db = new AppDatabase(file); bots = new BotRegistry(db.connection);
service = new BotCreationService(db.connection,bots,{userId:LOCAL_USER_ID,isAuthority:()=>true});
assert.equal(bots.getBot(bot.botId)!.displayName,"新名称","persists after reopen");
db.upsertSpace({id:spaceId,name:"用户自定空间"});
assert(rename("再次改名").ok); assert.equal(db.getSpace(spaceId)!.name,"用户自定空间");
db.connection.exec("CREATE TRIGGER reject_rename BEFORE UPDATE OF display_name ON bots BEGIN SELECT RAISE(ABORT, 'fixture'); END");
assert.equal(rename("事务回滚").ok,false); assert.equal(bots.getBot(bot.botId)!.displayName,"再次改名");
assert.deepEqual(db.connection.pragma("foreign_key_check"),[]);
db.close();
console.log("PASS rename validation, unicode duplicate, owner, stable identity/history/Work/config, conflict/replay, restart, custom space, rollback");

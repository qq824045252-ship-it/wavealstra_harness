const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const cp = require('node:child_process');
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'mybuddy-resident-'));
const executable = require('electron');
const fixture = path.resolve(__dirname, '../out/tests/resident-host-fixture.cjs');
const env = { ...process.env, USERPROFILE: home, HOME: home, APPDATA: path.join(home, 'AppData/Roaming'), LOCALAPPDATA: path.join(home, 'AppData/Local'), RESIDENT_FIXTURE_HOME: home };
delete env.ELECTRON_RUN_AS_NODE;
fs.mkdirSync(env.APPDATA, { recursive: true }); fs.mkdirSync(env.LOCALAPPDATA, { recursive: true });
const launch = () => cp.spawn(executable, [fixture], { env, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
const alive = pid => { try { process.kill(pid, 0); return true; } catch { return false; } };
const until = async (read, label) => { const end = Date.now() + 45000; while (Date.now() < end) { try { const result = await read(); if (result) return result; } catch {} await sleep(100); } throw Error(`timeout: ${label}`); };
const state = () => JSON.parse(fs.readFileSync(path.join(home, 'state.json'), 'utf8'));
const request = async (port, operation = '/state') => fetch(`http://127.0.0.1:${port}${operation}`).then(response => response.json());
const trace = () => fs.readFileSync(path.join(home, 'trace.jsonl'), 'utf8').trim().split('\n').map(JSON.parse);
let resident;
(async () => {
  const first = launch(); let errors = ''; first.stderr.on('data', chunk => { errors += chunk; });
  const initial = await until(() => state(), 'initial fixture ready');
  const original = await request(initial.port);
  assert.equal(original.notification.delivery, 'pending');
  assert.equal(original.authority, true);
  await request(initial.port, '/handoff');
  resident = await until(() => { const next = state(); return next.resident && next.pid !== initial.pid && next; }, 'independent resident ready');
  await until(() => !alive(initial.pid), 'old client PID exited');
  const delivered = await until(async () => { const current = await request(resident.port); return current.notification.delivery === 'sent' && current; }, 'original delivery recovered');
  assert.deepEqual(delivered.workId, original.workId);
  assert.equal(delivered.authority, true);
  assert.equal(trace().filter(row => row.event === 'external-effect').length, 1);
  const reopened = launch();
  await until(async () => (await request(resident.port)).windows === 1, 'UI reopens on same resident');
  await until(() => reopened.exitCode !== null, 'reopening client exited');
  assert.equal((await request(resident.port)).pid, resident.pid);
  await request(resident.port, '/close-ui');
  assert.equal((await request(resident.port)).windows, 0);
  assert.equal(alive(resident.pid), true);
  await sleep(200);
  assert.equal(trace().filter(row => row.event === 'external-effect').length, 1, 'reopen/close must not resend');
  const events = trace();
  assert.ok(events.findIndex(row => row.event === 'writers-closed' && row.pid === initial.pid) < events.findIndex(row => row.event === 'ready' && row.pid === resident.pid));
  await request(resident.port, '/stop');
  await until(() => !alive(resident.pid), 'stop assistant exits resident');
  await sleep(300);
  assert.equal(trace().filter(row => row.event === 'ready').length, 2, 'stop must not relaunch');
  console.log(`resident-host-test: PASS originalWork=${original.workId.work_id} clientPid=${initial.pid} residentPid=${resident.pid} externalEffects=1`);
})().catch(error => { console.error(error, '\nfixture:', home); process.exitCode = 1; }).finally(async () => {
  if (resident && alive(resident.pid)) { try { await request(resident.port, '/stop'); } catch {} }
});

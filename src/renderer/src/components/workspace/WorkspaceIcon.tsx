export const workspaceIconColors = {
  default: { label: "默认", value: undefined },
  red: { label: "红色", value: "light-dark(#b4233a, #ff8c9a)" },
  orange: { label: "橙色", value: "light-dark(#b94d16, #ffad79)" },
  amber: { label: "金色", value: "light-dark(#946200, #f5c65c)" },
  green: { label: "绿色", value: "light-dark(#217548, #75d99d)" },
  teal: { label: "青色", value: "light-dark(#147773, #67d7d1)" },
  blue: { label: "蓝色", value: "light-dark(#245ac5, #8cb5ff)" },
  violet: { label: "紫色", value: "light-dark(#6c46bd, #c3aaff)" },
  pink: { label: "粉色", value: "light-dark(#aa3b80, #f4a3d4)" },
} satisfies Record<WorkspaceIconAppearance["color"], { label: string; value: string | undefined }>;

export default function WorkspaceIcon({ icon, size, open = false }: {
  icon?: WorkspaceIconAppearance;
  size: number;
  open?: boolean;
}): React.JSX.Element {
  const shape = icon?.shape ?? "folder";
  const glyph = shape === "folder" && open ? "folder-open" : workspaceIconGlyphs[shape];
  const color = workspaceIconColors[icon?.color ?? "default"].value;
  return <UiIcon name={glyph} size={size} accent={!color} style={color ? { color } : undefined} />;
}

import { Type } from "typebox";
import { browserCollectionSchema } from "./browser/BrowserCollectionSchema";
import { browserConditionSchema } from "./browser/BrowserConditions";
import { browserAgentPolicy } from "./BrowserAgentPolicy";

export const BROWSER_EXEC_ACTIONS = ["status", "navigate", "read", "click", "fill", "drag", "press", "screenshot", "find", "inspect", "wait_for", "scroll", "hover", "select", "check", "frames", "accessibility", "assert", "diagnostics", "dialog", "open", "select_tab", "close", "back", "forward", "reload", "upload", "collect", "click_at", "scroll_at", "handoff", "resume"] as const;

export const browserExecSchema = Type.Object({
  action: Type.Union(BROWSER_EXEC_ACTIONS.map(action => Type.Literal(action))),
  files: Type.Optional(Type.Array(Type.String({ minLength: 1, maxLength: 4000 }), { minItems: 1, maxItems: 20 })),
  collection: Type.Optional(browserCollectionSchema),
  maxSteps: Type.Optional(Type.Integer({ minimum: 1, maximum: 50 })),
  maxRows: Type.Optional(Type.Integer({ minimum: 1, maximum: 1000 })),
  captureId: Type.Optional(Type.String({ minLength: 1, maxLength: 200 })),
  x: Type.Optional(Type.Number({ minimum: 0, maximum: 100000 })),
  y: Type.Optional(Type.Number({ minimum: 0, maximum: 100000 })),
  reason: Type.Optional(Type.Union([Type.Literal("login"), Type.Literal("2fa")])),
  token: Type.Optional(Type.String({ minLength: 1, maxLength: 200 })),
  expect: Type.Optional(Type.Array(browserConditionSchema, { minItems: 1, maxItems: 16 })),
  axNodeId: Type.Optional(Type.String({ minLength: 1, maxLength: 200 })),
  documentId: Type.Optional(Type.String({ minLength: 1, maxLength: 200 })),
  traceCursor: Type.Optional(Type.Integer({ minimum: 0 })),
  dialog: Type.Optional(Type.Object({ id: Type.String({ minLength: 1, maxLength: 200 }), action: Type.Union([Type.Literal("accept"), Type.Literal("dismiss")]), promptText: Type.Optional(Type.String({ maxLength: 4000 })) }, { additionalProperties: false })),
  dialogRules: Type.Optional(Type.Array(Type.Object({ type: Type.Union(["alert", "confirm", "prompt", "beforeunload"].map(value => Type.Literal(value))), messageIncludes: Type.Optional(Type.String({ maxLength: 1000 })), answer: Type.Union([Type.Object({ action: Type.Literal("dismiss") }, { additionalProperties: false }), Type.Object({ action: Type.Literal("accept"), promptText: Type.Optional(Type.String({ maxLength: 4000 })) }, { additionalProperties: false })]) }, { additionalProperties: false }), { maxItems: 8 })),
  response: Type.Optional(Type.Object({ urlIncludes: Type.Optional(Type.String({ maxLength: 1000 })), status: Type.Optional(Type.Integer({ minimum: 100, maximum: 599 })) }, { additionalProperties: false })),
  download: Type.Optional(Type.Object({ urlIncludes: Type.Optional(Type.String({ maxLength: 1000 })), filename: Type.Optional(Type.String({ maxLength: 120 })) }, { additionalProperties: false })),
  reload: Type.Optional(Type.Boolean()),
  gadgetId: Type.Optional(Type.String({ minLength: 1, maxLength: 200 })),
  tabId: Type.Optional(Type.String({ maxLength: 200 })),
  frameId: Type.Optional(Type.String({ minLength: 1, maxLength: 200 })),
  url: Type.Optional(Type.String({ maxLength: 2_000 })),
  selector: Type.Optional(Type.String({ maxLength: 1_000 })),
  text: Type.Optional(Type.String({ maxLength: 100_000 })),
  key: Type.Optional(Type.String({ maxLength: 60 })),
  delta_x: Type.Optional(Type.Number({ minimum: -100_000, maximum: 100_000 })),
  delta_y: Type.Optional(Type.Number({ minimum: -100_000, maximum: 100_000 })),
  values: Type.Optional(Type.Array(Type.String({ maxLength: 1000 }), { maxItems: 80 })),
  button: Type.Optional(Type.Union([Type.Literal("left"), Type.Literal("right")])),
  clickCount: Type.Optional(Type.Union([Type.Literal(1), Type.Literal(2)])),
  modifiers: Type.Optional(Type.Array(Type.Union(["control", "alt", "shift", "meta"].map(value => Type.Literal(value))), { maxItems: 4, uniqueItems: true })),
  inputMode: Type.Optional(Type.Union([Type.Literal("replace"), Type.Literal("sequential")])),
  delayMs: Type.Optional(Type.Integer({ minimum: 0, maximum: 1000 })),
  dateType: Type.Optional(Type.Union(["date", "time", "datetime-local", "month", "week"].map(value => Type.Literal(value)))),
  dragMode: Type.Optional(Type.Union([Type.Literal("pointer"), Type.Literal("html")])),
  dragTo: Type.Optional(Type.String({ minLength: 1, maxLength: 1000 })),
  checked: Type.Optional(Type.Boolean()),
  hover: Type.Optional(Type.Array(Type.Object({
    selector: Type.Optional(Type.String({ minLength: 1, maxLength: 1000 })),
    role: Type.Optional(Type.String({ minLength: 1, maxLength: 200 })),
    name: Type.Optional(Type.String({ minLength: 1, maxLength: 1000 })),
    text: Type.Optional(Type.String({ minLength: 1, maxLength: 4000 })),
  }, { additionalProperties: false }), { minItems: 1, maxItems: 8 })),
  max_chars: Type.Optional(Type.Integer({ minimum: 1_000, maximum: 100_000 })),
  mode: Type.Optional(Type.Union([Type.Literal("text"), Type.Literal("interactive")])),
  role: Type.Optional(Type.String({ maxLength: 200 })),
  name: Type.Optional(Type.String({ maxLength: 1_000 })),
  within: Type.Optional(Type.String({ minLength: 1, maxLength: 1_000 })),
  exact: Type.Optional(Type.Boolean()),
  label: Type.Optional(Type.String({ minLength: 1, maxLength: 1_000 })),
  placeholder: Type.Optional(Type.String({ minLength: 1, maxLength: 1_000 })),
  testId: Type.Optional(Type.String({ minLength: 1, maxLength: 1_000 })),
  cursor: Type.Optional(Type.String({ maxLength: 300 })),
  offset: Type.Optional(Type.Integer({ minimum: 0 })),
  element_offset: Type.Optional(Type.Integer({ minimum: 0 })),
  timeout_ms: Type.Optional(Type.Integer({ minimum: 100, maximum: 30_000 })),
  state: Type.Optional(Type.Union([Type.Literal("attached"), Type.Literal("detached"), Type.Literal("visible"), Type.Literal("hidden")])),
  after: Type.Optional(Type.Object({
    selector: Type.Optional(Type.String({ maxLength: 1_000 })),
    role: Type.Optional(Type.String({ maxLength: 200 })),
    name: Type.Optional(Type.String({ maxLength: 1_000 })),
    state: Type.Optional(Type.Union([Type.Literal("attached"), Type.Literal("detached"), Type.Literal("visible"), Type.Literal("hidden")])),
    mode: Type.Optional(Type.Union([Type.Literal("text"), Type.Literal("interactive")])),
    maxChars: Type.Optional(Type.Integer({ minimum: 1_000, maximum: 100_000 })),
  }, { additionalProperties: false })),
}, { additionalProperties: false });

/** Codemode receives the same host result as native calls, without parsing prose. */
export const browserStructuredOutputSchema = Type.Object({
  isError: Type.Boolean(),
  action: Type.Optional(Type.String()), tabId: Type.Optional(Type.String()),
  url: Type.Optional(Type.String()), title: Type.Optional(Type.String()), text: Type.Optional(Type.String()),
  nextCursor: Type.Optional(Type.String()), textTruncated: Type.Optional(Type.Boolean()),
  elements: Type.Optional(Type.Array(Type.Object({ selector: Type.String(), tag: Type.String(), label: Type.String() }, { additionalProperties: true }))),
  outcome: Type.Optional(Type.Object({ dispatch: Type.Union([Type.Literal("not_started"), Type.Literal("dispatched")]), effect: Type.Union([Type.Literal("none"), Type.Literal("unknown"), Type.Literal("confirmed")]) })),
  code: Type.Optional(Type.String()), error: Type.Optional(Type.String()),
}, { additionalProperties: true });

